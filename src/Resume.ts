function validateMarkers(
  root: Document | Element | ShadowRoot,
  events: Readonly<Record<string, typeof EventEntrySchema.Type>>,
  eventTypes: ReadonlySet<EventType>,
  installationId: string | undefined,
): Effect.Effect<
  void,
  | ResumeUnknownEventMarkerError
  | ResumeDuplicateEventMarkerError
  | ResumeMissingEventMarkerError
  | ResumeEventTypeMismatchError
> {
  return Effect.gen(function* () {
    const counts = new Map<string, number>();
    const inspectedEventTypes = new Set(eventTypes);
    for (const eventType of discoverMarkerEventTypes(root)) {
      inspectedEventTypes.add(eventType);
    }
    for (const eventType of inspectedEventTypes) {
      const selector = `[data-af-event-${eventType}]`;
      const targets = [...root.querySelectorAll(selector)];
      if ("getAttribute" in root && typeof root.getAttribute === "function") {
        if (root.getAttribute(`data-af-event-${eventType}`) !== null) {
          targets.unshift(root as Element);
        }
      }
      for (const target of targets) {
        const marker = target.getAttribute(`data-af-event-${eventType}`);
        if (marker === null) continue;
        const eventId = unscopeEventMarker(marker, installationId);
        if (eventId === undefined) {
          return yield* new ResumeUnknownEventMarkerError({
            marker,
            eventType,
            message: `Event marker "${marker}" does not belong to this installation${
              installationId === undefined ? "" : ` ("${installationId}")`
            }.`,
          });
        }
        const entry = events[eventId];
        if (entry === undefined) {
          return yield* new ResumeUnknownEventMarkerError({
            marker,
            eventType,
            message: `No resume manifest entry exists for event marker "${marker}".`,
          });
        }
        if (entry.type !== eventType) {
          return yield* new ResumeEventTypeMismatchError({
            eventId: eventIdFromValidatedString(eventId),
            expected: entry.type,
            actual: eventType,
            message: `Event marker "${marker}" is attached to the wrong event type.`,
          });
        }
        counts.set(eventId, (counts.get(eventId) ?? 0) + 1);
      }
    }
    for (const [eventId, entry] of Object.entries(events)) {
      const count = counts.get(eventId) ?? 0;
      const decodedId = eventIdFromValidatedString(eventId);
      if (count === 0) {
        return yield* new ResumeMissingEventMarkerError({
          eventId: decodedId,
          eventType: entry.type,
          message: `Resume manifest event "${eventId}" has no DOM marker.`,
        });
      }
      if (count > 1) {
        return yield* new ResumeDuplicateEventMarkerError({
          eventId: decodedId,
          eventType: entry.type,
          count,
          message: `Resume event marker "${eventId}" appears ${count} times.`,
        });
      }
    }
  });
}

function validateActivationEventOwnership(
  root: Document | Element | ShadowRoot,
  events: Readonly<Record<string, typeof EventEntrySchema.Type>>,
  boundaries: ReadonlyMap<ComponentId, ComponentBoundary>,
  components: Readonly<Record<string, ComponentSnapshot>>,
): Effect.Effect<void, ResumeActivationEventOwnershipError> {
  return Effect.gen(function* () {
    const claimedTargets = new Map<string, EventId>();
    const depth = (boundary: ComponentBoundary): number => {
      let value = 0;
      let parentId = boundary.parentComponentId;
      while (parentId !== undefined) {
        value += 1;
        parentId = boundaries.get(parentId)?.parentComponentId;
      }
      return value;
    };
    for (const [rawEventId, entry] of Object.entries(events)) {
      if (entry.invocation !== ActivationProjection) continue;
      const eventId = eventIdFromValidatedString(rawEventId);
      const markerAttribute = `data-af-event-${entry.type}`;
      const targets = [...root.querySelectorAll(`[${markerAttribute}]`)];
      if ("getAttribute" in root && typeof root.getAttribute === "function") {
        if (root.getAttribute(markerAttribute) === rawEventId) {
          targets.unshift(root as Element);
        }
      }
      const target = targets.find(
        (candidate) => candidate.getAttribute(markerAttribute) === rawEventId,
      );
      if (target === undefined) {
        continue;
      }
      const boundary = [...boundaries.values()]
        .filter((candidate) => componentBoundaryContains(candidate, target))
        .sort((left, right) => depth(right) - depth(left))[0];
      if (boundary === undefined) {
        return yield* new ResumeActivationEventOwnershipError({
          eventId,
          eventType: entry.type,
          message: `Activation event "${eventId}" is not owned by a component boundary.`,
        });
      }
      if (components[boundary.componentId]?.activation === undefined) {
        return yield* new ResumeActivationEventOwnershipError({
          eventId,
          eventType: entry.type,
          message: `Activation event "${eventId}" belongs to component "${boundary.componentId}", which has no activation descriptor.`,
        });
      }
      const replayAttribute = replayTargetAttribute(entry.type);
      if (target.getAttribute(replayAttribute) !== entry.targetKey) {
        return yield* new ResumeActivationEventOwnershipError({
          eventId,
          eventType: entry.type,
          message: `Activation event "${eventId}" is missing replay target "${entry.targetKey}".`,
        });
      }
      const ownershipKey =
        `${boundary.componentId}:${entry.type}:${entry.targetKey}`;
      const existing = claimedTargets.get(ownershipKey);
      if (existing !== undefined) {
        return yield* new ResumeActivationEventOwnershipError({
          eventId,
          eventType: entry.type,
          message: `Activation events "${existing}" and "${eventId}" share replay target "${entry.targetKey}" in component "${boundary.componentId}".`,
        });
      }
      claimedTargets.set(ownershipKey, eventId);
    }
  });
}

function discoverMarkerEventTypes(
  root: Document | Element | ShadowRoot,
): ReadonlySet<EventType> {
  const eventTypes = new Set<EventType>();
  const candidates: Array<{
    readonly getAttributeNames?: () => string[];
  }> = [...root.querySelectorAll("*")];
  if (
    "getAttributeNames" in root &&
    typeof root.getAttributeNames === "function"
  ) {
    candidates.unshift(root);
  }
  for (const candidate of candidates) {
    if (typeof candidate.getAttributeNames !== "function") continue;
    for (const attribute of candidate.getAttributeNames()) {
      if (!attribute.startsWith("data-af-event-")) continue;
      const decoded = Schema.decodeUnknownOption(EventType)(
        attribute.slice("data-af-event-".length),
      );
      if (decoded._tag === "Some") {
        eventTypes.add(decoded.value);
      }
    }
  }
  return eventTypes;
}

/**
 * Strip the installation scope off one event marker (`DQ-009`).
 *
 * Markers are `"<installationId>:<eventId>"`. A marker whose scope does not
 * match this installation's id — or a malformed one — returns `undefined`
 * and is treated as belonging to some other installation, never resolved
 * against this manifest's table. Manifests without an `installationId`
 * (legacy payloads) accept only unqualified markers.
 */
function unscopeEventMarker(
  marker: string,
  installationId: string | undefined,
): string | undefined {
  const separator = marker.indexOf(":");
  if (separator < 0) {
    return installationId === undefined ? marker : undefined;
  }
  if (marker.indexOf(":", separator + 1) >= 0) return undefined;
  if (installationId === undefined) return undefined;
  return marker.slice(0, separator) === installationId
    ? marker.slice(separator + 1)
    : undefined;
}

function readMarker(target: EventTarget, eventType: EventType): string | null {
  const candidate = target as EventTarget & {
    readonly getAttribute?: (name: string) => string | null;
  };
  return typeof candidate.getAttribute === "function"
    ? candidate.getAttribute(`data-af-event-${eventType}`)
    : null;
}

function eventPathWithinRoot(
  event: Event,
  root: Document | Element | ShadowRoot,
): ReadonlyArray<EventTarget> {
  const composed =
    typeof event.composedPath === "function" ? event.composedPath() : [];
  const path: EventTarget[] = composed.length > 0 ? [...composed] : [];
  if (path.length === 0) {
    let current = event.target as
      | (EventTarget & {
          readonly parentNode?: EventTarget | null;
          readonly parentElement?: EventTarget | null;
          readonly host?: EventTarget | null;
        })
      | null;
    while (current !== null) {
      path.push(current);
      if (current === root) break;
      current =
        current.parentNode ?? current.parentElement ?? current.host ?? null;
    }
  }
  const rootIndex = path.indexOf(root);
  return rootIndex === -1 ? [] : path.slice(0, rootIndex + 1);
}

function statePoliciesFromPlan(
  steps: ReadonlyArray<Component.SetupStepInspection>,
): {
  readonly policies: ReadonlyMap<string, AnyBindingSnapshotPolicy>;
  readonly unsupportedReason?: string;
} {
  const policies = new Map<string, AnyBindingSnapshotPolicy>();
  const visit = (
    current: ReadonlyArray<Component.SetupStepInspection>,
  ): string | undefined => {
    for (const step of current) {
      if (step.kind === "effect") {
        return "State-only restoration cannot skip a setup side-effect step.";
      }
      if (step.kind === "value") {
        return `Synchronous setup binding "${step.name ?? "<unnamed>"}" is not restorable in the state-only slice.`;
      }
      if (step.kind === "fragment") {
        if (step.plan?.kind !== "named") {
          return "State-only restoration cannot traverse an opaque setup fragment.";
        }
        const nested = visit(step.plan.steps);
        if (nested !== undefined) return nested;
        continue;
      }
      if (step.name === undefined) {
        return "A named setup binding is missing its binding name.";
      }
      if (step.resume === undefined) {
        return `Binding "${step.name}" has no state snapshot policy and requires fallback activation.`;
      }
      if (policies.has(step.name)) {
        return `Binding "${step.name}" appears more than once in the setup plan.`;
      }
      policies.set(step.name, step.resume);
    }
    return undefined;
  };

  const unsupportedReason = visit(steps);
  return {
    policies,
    ...(unsupportedReason === undefined ? {} : { unsupportedReason }),
  };
}

