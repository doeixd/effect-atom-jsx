function childNodesOf(value: unknown): ReadonlyArray<unknown> {
  if (typeof value !== "object" || value === null) return [];
  const childNodes = (
    value as {
      readonly childNodes?: ArrayLike<unknown>;
    }
  ).childNodes;
  return childNodes === undefined ? [] : Array.from(childNodes);
}

function nativeTreeWalker(root: unknown): TreeWalker | undefined {
  if (typeof root !== "object" || root === null) return undefined;
  const node = root as Node;
  const document = node.nodeType === 9
    ? node as Document
    : node.ownerDocument;
  if (document === null || typeof document?.createTreeWalker !== "function") {
    return undefined;
  }
  try {
    // SHOW_ALL is deliberately inlined so scanning also works in DOM
    // implementations that do not publish a global NodeFilter constructor.
    return document.createTreeWalker(node, 0xffff_ffff);
  } catch {
    // Tests and renderer adapters may expose DOM-shaped nodes without a
    // complete TreeWalker implementation. Preserve the structural fallback.
    return undefined;
  }
}

function* nodesInDocumentOrder(root: unknown): Generator<unknown> {
  const walker = nativeTreeWalker(root);
  if (walker !== undefined) {
    let node = walker.nextNode();
    while (node !== null) {
      yield node;
      node = walker.nextNode();
    }
    return;
  }

  // Avoid this path in browsers: reading childNodes materializes a live
  // NodeList on every visited DOM node, and browsers retain those wrappers
  // with the nodes. The fallback remains useful for renderer-neutral tests.
  const stack = [...childNodesOf(root)].reverse();
  while (stack.length > 0) {
    const node = stack.pop()!;
    yield node;
    const children = childNodesOf(node);
    for (let index = children.length - 1; index >= 0; index -= 1) {
      stack.push(children[index]);
    }
  }
}

function* nodesInDocumentOrderIncludingRoot(
  root: unknown,
): Generator<unknown> {
  yield root;
  yield* nodesInDocumentOrder(root);
}

function componentBoundaryComment(node: unknown): string | undefined {
  if (typeof node !== "object" || node === null) return undefined;
  const candidate = node as {
    readonly nodeType?: number;
    readonly nodeName?: string;
    readonly data?: unknown;
    readonly nodeValue?: unknown;
    readonly textContent?: unknown;
    readonly _commentText?: unknown;
  };
  if (candidate.nodeType !== 8 && candidate.nodeName !== "#comment") {
    return undefined;
  }
  const value =
    candidate.data ??
    candidate.nodeValue ??
    candidate._commentText ??
    candidate.textContent;
  return typeof value === "string" ? value : undefined;
}

