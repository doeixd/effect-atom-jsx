const defaultMaximumPayloadBytes = 64 * 1024;
const activeClientInstallations = new WeakMap<object, symbol>();

function largestManifestEntry(manifest: Manifest): {
  readonly kind: "event" | "component" | "expression";
  readonly id: string;
  readonly bytes: number;
  readonly bindingName?: string;
} | undefined {
  const candidates: Array<{
    readonly kind: "event" | "component" | "expression";
    readonly id: string;
    readonly bytes: number;
    readonly bindingName?: string;
  }> = [];
  const jsonBytes = (id: string, entry: unknown): number =>
    new TextEncoder().encode(JSON.stringify({ [id]: entry })).byteLength;
  const measure = (
    kind: "event" | "component" | "expression",
    entries: Readonly<Record<string, unknown>>,
  ): void => {
    for (const [id, entry] of Object.entries(entries)) {
      candidates.push({ kind, id, bytes: jsonBytes(id, entry) });
    }
  };
  measure("event", manifest.events);
  if (manifest.version !== 1) {
    // Attribution must reach the *binding*: a component entry names the
    // container, but the first real payload collision is only debuggable if
    // the error points at which binding inside it dominates.
    for (const [id, entry] of Object.entries(manifest.components)) {
      let bindingName: string | undefined;
      let bindingBytes = -1;
      for (const [name, snapshot] of Object.entries(entry.bindings)) {
        const bytes = jsonBytes(name, snapshot);
        if (bytes > bindingBytes) {
          bindingName = name;
          bindingBytes = bytes;
        }
      }
      candidates.push({
        kind: "component",
        id,
        bytes: jsonBytes(id, entry),
        ...(bindingName === undefined ? {} : { bindingName }),
      });
    }
  }
  measure("expression", expressionEntriesOf(manifest));
  return candidates.reduce<
    | {
        readonly kind: "event" | "component" | "expression";
        readonly id: string;
        readonly bytes: number;
        readonly bindingName?: string;
      }
    | undefined
  >(
    (largest, candidate) =>
      largest === undefined || candidate.bytes > largest.bytes
        ? candidate
        : largest,
    undefined,
  );
}

/**
 * Collect portable SSR events around a synchronous render.
 *
 * The render callback will normally call `renderToString`. Descriptor and
 * manifest finalization remain Effect-native and use the configured
 * `Serialization` service.
 */
let nextAutoInstallationOrdinal = 0;

/**
 * Validate (or mint) one installation scope id (`DQ-009`). `:` is the marker
 * separator and is rejected here, at collection time — an ambiguous marker
 * must never reach served HTML.
 */
function resolveInstallationId(
  requested: string | undefined,
): Effect.Effect<string, ResumeConfigurationError> {
  if (requested === undefined) {
    const minted = `p${nextAutoInstallationOrdinal}`;
    nextAutoInstallationOrdinal += 1;
    return Effect.succeed(minted);
  }
  if (requested.length === 0 || requested.includes(":")) {
    return Effect.fail(
      new ResumeConfigurationError({
        message: `Installation id ${JSON.stringify(requested)} is invalid: ids must be non-empty and must not contain ":" (the reserved marker separator).`,
      }),
    );
  }
  return Effect.succeed(requested);
}

export function collect(
  render: () => string,
  options: CollectOptions,
): Effect.Effect<
  CollectionResult,
  CollectionError,
  Serialization.SerializationService
> {
  return collectInternal(
    (session) =>
      Effect.try({
        try: () => runInResumeSession(session, render),
        catch: (error) =>
          new ResumeRenderError({
            message: `Resume render failed: ${String(error)}`,
          }),
      }),
    options,
  ).pipe(Effect.withSpan("Resume.collect"));
}

/**
 * Async-capable collection (M11.1/M11.2): the render is an Effect that may
 * suspend between synchronous render passes while other requests render to
 * completion. The session and the render's own server document travel on the
 * fiber (`ServerRenderStateTag`) — inherited by forked children — and
 * `renderToString` installs them for exactly its own synchronous slices, so
 * two interleaved renders share no session, no document, and no diagnostics.
 */
export function collectAsync<E = never, R = never>(
  render: () => Effect.Effect<string | ReadonlyArray<string>, E, R>,
  options: CollectOptions,
): Effect.Effect<
  CollectionResult,
  CollectionError | E,
  Serialization.SerializationService | R
> {
  return collectInternal(
    (session) =>
      Effect.suspend(render).pipe(
        // A render effect may legitimately produce several rendered chunks
        // (e.g. `Effect.all` over per-region renders); normalize to one
        // document string.
        Effect.map((value) =>
          typeof value === "string" ? value : value.join("")
        ),
        Effect.provideService(ServerRenderStateTag, {
          session,
          document: createServerDocument(),
          ...(options.deadline === undefined
            ? {}
            : { deadline: options.deadline }),
        }),
        // The request scope: resources a suspended setup acquires are
        // released exactly once when the render completes — including setups
        // the deadline interrupted.
        Effect.scoped,
      ),
    options,
  ).pipe(Effect.withSpan("Resume.collectAsync"));
}

const asyncSetupTimedOut = Symbol.for(
  "@effect-atom-jsx/Resume/asyncSetupTimedOut",
);

/**
 * Render one component inside a `collectAsync` render, awaiting its setup
 * (M11.2, ratified `DQ-005`: a separate entry point beside the synchronous
 * path, so "no regression to the synchronous renderer" stays checkable at
 * the type level).
 *
 * The setup Effect may suspend freely; the view then renders from the
 * committed bindings inside one synchronous serialization slice. If the
 * request's `deadline` elapses first, the region degrades to the existing
 * fail-closed activation fallback: one `"async-setup-timeout"` diagnostic
 * attributed to this region, empty HTML, and nothing registered in the
 * manifest (the ghost-snapshot rule — never register what never rendered).
 */
export function renderComponentAsync<Props, Req, E, Bindings, SlotContract>(
  component: Component.Component<Props, Req, E, Bindings, SlotContract>,
  props: Props,
): Effect.Effect<string, E | ResumeRenderError, Req> {
  return Effect.gen(function* () {
    const state = currentServerRenderState();
    if (state === undefined) {
      return yield* new ResumeRenderError({
        message:
          "renderComponentAsync must run inside a Resume.collectAsync render.",
      });
    }
    // `Component.from` components surface their setup Effect as the view
    // value; settle nested Effects until a renderable value remains — that
    // suspension is exactly what this entry point exists to await.
    const settleDeep = (candidate: unknown): Effect.Effect<unknown, E, Req> =>
      Effect.isEffect(candidate)
        ? (candidate as Effect.Effect<unknown, E, Req>).pipe(
            Effect.flatMap(settleDeep),
          )
        : Effect.succeed(candidate);
    const rendered = Component.renderEffect(component, props).pipe(
      Effect.flatMap(settleDeep),
    );
    const value = yield* (state.deadline === undefined
      ? rendered
      : rendered.pipe(
          Effect.timeoutOrElse({
            duration: state.deadline,
            orElse: () =>
              Effect.sync(() => {
                state.session.diagnostics.push({
                  code: "async-setup-timeout",
                  phase: "collect",
                  severity: "warning",
                  disposition: "fallback-required",
                  reason:
                    "Component setup exceeded the async render deadline; the region falls back to activation.",
                });
                return asyncSetupTimedOut;
              }),
          }),
        ));
    if (value === asyncSetupTimedOut) return "";
    return yield* Effect.try({
      try: () =>
        runStreamSlice(
          state.document,
          state.session as ReturnType<typeof makeResumeSession>,
          () => serverValueToHTML(value),
        ),
      catch: (error) =>
        new ResumeRenderError({
          message: `Async component render failed during serialization: ${String(error)}`,
        }),
    });
  }).pipe(Effect.withSpan("Resume.renderComponentAsync"));
}

function collectInternal<E, R>(
  produceHtml: (
    session: ReturnType<typeof makeResumeSession>,
  ) => Effect.Effect<string, E, R>,
  options: CollectOptions,
): Effect.Effect<
  CollectionResult,
  CollectionError | E,
  Serialization.SerializationService | R
> {
  return Effect.gen(function* () {
    const buildId = yield* Schema.decodeUnknownEffect(Portable.BuildId)(
      options.buildId,
    ).pipe(
      Effect.catchTag("SchemaError", (error) =>
        Effect.fail(
          new ResumeConfigurationError({
            message: `Invalid resume build ID: ${String(error)}`,
          }),
        ),
      ),
    );
    const maximumBytes = options.maxPayloadBytes ?? defaultMaximumPayloadBytes;
    if (!Number.isSafeInteger(maximumBytes) || maximumBytes <= 0) {
      return yield* new ResumeConfigurationError({
        message: "maxPayloadBytes must be a positive safe integer.",
      });
    }
    const installationId = yield* resolveInstallationId(options.installationId);

    const session = makeResumeSession(installationId);
    let html = yield* produceHtml(session);
    finalizeResumeSession(session);

    const events: Record<string, typeof EventEntrySchema.Type> = {};
    for (const pending of session.events) {
      const eventId = eventIdFromValidatedString(pending.id);
      const eventType = eventTypeFromValidatedString(pending.eventType);
      if (pending.kind === "activation") {
        events[eventId] = {
          type: eventType,
          invocation: pending.invocation,
          projection: pending.projection,
          targetKey: pending.targetKey,
        };
        continue;
      }
      const descriptor = yield* Portable.describe(pending.executable).pipe(
        Effect.catchTag("PortableCaptureEncodeError", (error) =>
          Effect.fail(
            new ResumeDescriptorError({
              eventId,
              codeId: pending.executable.code.id,
              message: error.message,
            }),
          ),
        ),
      );
      if (descriptor.buildId !== buildId) {
        return yield* new ResumeBuildMismatchError({
          eventId,
          expected: buildId,
          actual: descriptor.buildId,
          message: `Event "${eventId}" references code from a different build.`,
        });
      }
      events[eventId] = {
        type: eventType,
        invocation: pending.invocation,
        code: descriptor,
      };
    }

    const components: Record<string, ComponentSnapshot> = Object.create(null);
    const encodedBindingValues = new Map<string, unknown>();
    const dehydratedAt = Date.now();
    for (const pending of session.components) {
      const componentId = componentIdFromValidatedString(pending.id);
      if (!session.renderedComponentIds.has(pending.id)) {
        session.diagnostics.push({
          code: "missing-component-boundary",
          phase: "collect",
          severity: "warning",
          disposition: "fallback-required",
          componentId,
          reason: `Component "${componentId}" committed resumable bindings but did not render an addressable DOM region.`,
        });
        continue;
      }
      const activation =
        pending.activation === undefined
          ? undefined
          : yield* Portable.describe(pending.activation).pipe(
              Effect.catchTag("PortableCaptureEncodeError", (error) =>
                Effect.fail(
                  new ResumeComponentActivationDescriptorError({
                    componentId,
                    codeId: pending.activation!.code.id,
                    message: `Component "${componentId}" activation props failed schema encoding: ${error.message}`,
                  }),
                ),
              ),
            );
      if (activation !== undefined && activation.buildId !== buildId) {
        return yield* new ResumeComponentActivationBuildMismatchError({
          componentId,
          expected: buildId,
          actual: activation.buildId,
          message: `Component "${componentId}" activation references code from a different build.`,
        });
      }
      const bindings: Record<string, BindingSnapshot> = Object.create(null);
      for (const binding of pending.bindings) {
        const bindingName = yield* Schema.decodeUnknownEffect(BindingName)(
          binding.name,
        ).pipe(
          Effect.catchTag("SchemaError", (error) =>
            Effect.fail(
              new ResumeStateSnapshotEncodeError({
                componentId,
                binding: binding.name,
                message: `Invalid snapshot binding name "${binding.name}": ${String(error)}`,
              }),
            ),
          ),
        );
        const snapshotLabel =
          binding.kind === "state" ? "State snapshot" : "Query snapshot";
        const encoded = yield* Schema.encodeEffect(binding.policy.schema)(
          binding.value,
        ).pipe(
          Effect.catchTag("SchemaError", (error) =>
            Effect.fail(
              new ResumeStateSnapshotEncodeError({
                componentId,
                binding: bindingName,
                message: `${snapshotLabel} "${componentId}/${bindingName}" failed schema encoding: ${String(error)}`,
              }),
            ),
          ),
        );
        const issue = jsonValueIssue(encoded, snapshotLabel);
        if (issue !== undefined) {
          return yield* new ResumeStateSnapshotEncodeError({
            componentId,
            binding: bindingName,
            message: issue,
          });
        }
        encodedBindingValues.set(
          bindingReactivityKey(componentId, bindingName),
          encoded,
        );
        if (binding.kind === "state") {
          Object.defineProperty(bindings, bindingName, {
            enumerable: true,
            value: {
              kind: "state",
              key: `${componentId}/${bindingName}`,
              value: encoded,
              dehydratedAt,
            },
          });
          continue;
        }
        const executor = yield* Portable.describe(binding.executable).pipe(
          Effect.catchTag("PortableCaptureEncodeError", (error) =>
            Effect.fail(
              new ResumeQueryExecutorDescriptorError({
                componentId,
                binding: bindingName,
                codeId: binding.executable.code.id,
                message: `Query executor for "${componentId}/${bindingName}" failed capture encoding: ${error.message}`,
              }),
            ),
          ),
        );
        if (executor.buildId !== buildId) {
          return yield* new ResumeQueryExecutorBuildMismatchError({
            componentId,
            binding: bindingName,
            expected: buildId,
            actual: executor.buildId,
            message: `Query executor for "${componentId}/${bindingName}" references code from a different build.`,
          });
        }
        Object.defineProperty(bindings, bindingName, {
          enumerable: true,
          value: {
            kind: "query",
            key: `${componentId}/${bindingName}`,
            value: encoded,
            dehydratedAt,
            executor,
            reactivityKeys: binding.reactivityKeys,
          },
        });
      }
      Object.defineProperty(components, componentId, {
        enumerable: true,
        value: {
          ...(pending.definitionName === undefined
            ? {}
            : { definitionName: pending.definitionName }),
          region: {
            kind: "comment-pair",
          },
          ...(activation === undefined ? {} : { activation }),
          bindings,
        },
      });
    }

    const expressions: Record<string, ExpressionEntryV5> =
      Object.create(null);
    for (const pending of session.expressions) {
      const expressionId = expressionIdFromValidatedString(pending.id);
      if (
        pending.ownerComponentId !== undefined
        && !Object.prototype.hasOwnProperty.call(
          components,
          pending.ownerComponentId,
        )
      ) {
        // A fallback-required component that never acquired a durable region
        // cannot own an independently installable expression. Remove the
        // reserved sentinels from the returned HTML together with the manifest
        // entry so an adapter that proceeds after diagnostics does not turn
        // the warning into an unknown-owner installation failure.
        if (
          pending.target.kind === "text"
          || pending.target.kind === "structural"
        ) {
          html = html
            .replace(`<!--af:expr:${expressionId}:start-->`, "")
            .replace(`<!--af:expr:${expressionId}:end-->`, "");
          if (pending.target.kind === "structural") {
            html = html.replace(
              new RegExp(`<!--af:row:${expressionId}:[^>]*-->`, "g"),
              "",
            );
          }
        } else {
          html = removeExpressionElementMarkerId(html, expressionId);
        }
        continue;
      }
      const dependencyValues = (
        pending.inputs ?? pending.deps
      ).map((key) => encodedBindingValues.get(key));
      yield* pending.validateDependencies(dependencyValues).pipe(
        Effect.catchTag("ExpressionDependencyDecodeError", (error) =>
          Effect.fail(
            new ResumeExpressionInputDecodeError({
              expressionId,
              codeId: pending.executable.code.id,
              message:
                `Expression "${expressionId}" cannot decode the same dependency snapshot the dormant client will receive: ${error.message}`,
            }),
          ),
        ),
      );
      const descriptor = yield* Portable.describe(pending.executable).pipe(
        Effect.catchTag("PortableCaptureEncodeError", (error) =>
          Effect.fail(
            new ResumeExpressionDescriptorError({
              expressionId,
              codeId: pending.executable.code.id,
              message: `Expression "${expressionId}" captures failed schema encoding: ${error.message}`,
            }),
          ),
        ),
      );
      if (descriptor.buildId !== buildId) {
        return yield* new ResumeExpressionBuildMismatchError({
          expressionId,
          expected: buildId,
          actual: descriptor.buildId,
          message: `Expression "${expressionId}" references code from a different build.`,
        });
      }
      Object.defineProperty(expressions, expressionId, {
        enumerable: true,
        value: {
          // Validated by the SSR registrar against the same allowlist the
          // schemas below encode; the manifest is schema-serialized before it
          // leaves `collect`, so a drifted name still fails closed here.
          target: pending.target as ExpressionTarget,
          code: descriptor,
          deps: pending.deps,
          ...(pending.inputs === undefined
            ? {}
            : { inputs: pending.inputs }),
          ...(pending.ownerComponentId === undefined
            ? {}
            : {
                component: componentIdFromValidatedString(
                  pending.ownerComponentId,
                ),
              }),
        },
      });
    }

    // A structural entry is the only thing that needs the v5 schema; without
    // one the manifest stays at v4 so older clients keep decoding it.
    const hasStructuralExpression = Object.values(expressions).some(
      (entry) => entry.target.kind === "structural",
    );
    const manifest: Manifest =
      Object.keys(expressions).length > 0
        ? hasStructuralExpression
          ? {
              version: 5,
              buildId,
              installationId,
              events,
              components,
              expressions,
            }
          : {
              version: 4,
              buildId,
              installationId,
              events,
              components,
              // No structural entries exist on this branch, so the record
              // satisfies the narrower v4 entry union.
              expressions: expressions as Record<string, ExpressionEntryV4>,
            }
        : Object.keys(components).length === 0
        ? {
            version: 1,
            buildId,
            installationId,
            events,
          }
        : {
            version: 2,
            buildId,
            installationId,
            events,
            components,
          };
    const serialization = yield* Serialization.Tag;
    // DQ-012: stamp the serializer identity beside the build id. The default
    // codec stays unstamped so legacy payloads are byte-identical.
    const stampedManifest: Manifest =
      serialization.id === Serialization.defaultSerializerId
        ? manifest
        : { ...manifest, serializer: serialization.id };
    const serializedManifest = yield* serialization
      .serialize(ManifestSchema, stampedManifest)
      .pipe(
        Effect.catchTag("SchemaError", (error) =>
          Effect.fail(
            new ResumeManifestEncodeError({
              message: `Resume manifest encoding failed: ${String(error)}`,
            }),
          ),
        ),
      );
    const actualBytes = new TextEncoder().encode(serializedManifest).byteLength;
    if (actualBytes > maximumBytes) {
      const largest = largestManifestEntry(manifest);
      return yield* new ResumePayloadTooLargeError({
        maximumBytes,
        actualBytes,
        ...(largest === undefined
          ? {}
          : {
              largestEntryKind: largest.kind,
              largestEntryId: largest.id,
              largestEntryBytes: largest.bytes,
              ...(largest.bindingName === undefined
                ? {}
                : { largestBindingName: largest.bindingName }),
            }),
        message: `Resume manifest is ${actualBytes} bytes, exceeding the ${maximumBytes}-byte limit.${
          largest === undefined
            ? ""
            : ` The largest ${largest.kind} entry is "${largest.id}" at approximately ${largest.bytes} bytes${
                largest.bindingName === undefined
                  ? ""
                  : ` (largest binding: "${largest.bindingName}")`
              }.`
        }`,
      });
    }

    return {
      html,
      manifest: stampedManifest,
      serializedManifest,
      script: `<script type="application/json" data-af-resume>${serializedManifest}</script>`,
      diagnostics: Object.freeze([...session.diagnostics]),
    };
  });
}

/**
 * Decode and validate a serialized resume manifest against the running client
 * build. The expected build ID comes from the client deployment, never from
 * the payload itself.
 */
function readSerializerEnvelopeStamp(wire: string): string | undefined {
  try {
    const parsed = JSON.parse(wire) as
      | { readonly [Serialization.serializerEnvelopeKey]?: unknown }
      | null;
    const stamp =
      typeof parsed === "object" && parsed !== null
        ? parsed[Serialization.serializerEnvelopeKey]
        : undefined;
    return typeof stamp === "string" ? stamp : undefined;
  } catch {
    // Not JSON at the outer layer: let the codec's own decode classify it.
    return undefined;
  }
}

export function decodeManifest(
  serialized: string,
  expectedBuildId: string,
  options: DecodeManifestOptions = {},
): Effect.Effect<
  ValidatedManifest,
  ManifestDecodeError,
  Serialization.SerializationService
> {
  return Effect.gen(function* () {
    const expected = yield* decodeBuildId(expectedBuildId);
    const maximumBytes = options.maxPayloadBytes ?? defaultMaximumPayloadBytes;
    if (!Number.isSafeInteger(maximumBytes) || maximumBytes <= 0) {
      return yield* new ResumeConfigurationError({
        message: "maxPayloadBytes must be a positive safe integer.",
      });
    }
    const actualBytes = new TextEncoder().encode(serialized).byteLength;
    if (actualBytes > maximumBytes) {
      return yield* new ResumePayloadTooLargeError({
        maximumBytes,
        actualBytes,
        message: `Resume manifest is ${actualBytes} bytes, exceeding the ${maximumBytes}-byte limit.`,
      });
    }
    const serialization = yield* Serialization.Tag;
    // DQ-012: the serializer gate fires BEFORE any value decodes. Every codec
    // emits JSON at the outermost layer, so the envelope stamp is readable
    // without engaging the value codec; a payload stamped by a different
    // serializer is rejected here, never misdecoded.
    const envelopeStamp = readSerializerEnvelopeStamp(serialized);
    if (envelopeStamp !== undefined && envelopeStamp !== serialization.id) {
      return yield* new ResumeSerializerMismatchError({
        expected: serialization.id,
        actual: envelopeStamp,
        message: `The resume manifest was serialized by "${envelopeStamp}", but this client's Serialization layer is "${serialization.id}".`,
      });
    }
    const manifest = rememberValidatedManifest(
      yield* serialization
        .deserialize(ManifestSchema, serialized)
        .pipe(
          Effect.catchTag("SchemaError", (error) =>
            Effect.fail(
              new ResumeManifestDecodeError({
                message: `Resume manifest decoding failed: ${String(error)}`,
              }),
            ),
          ),
        ),
    );
    if (manifest.buildId !== expected) {
      return yield* new ResumeClientBuildMismatchError({
        expected,
        actual: manifest.buildId,
        message: "The resume manifest belongs to a different client build.",
      });
    }
    if (
      manifest.serializer !== undefined
      && manifest.serializer !== serialization.id
    ) {
      return yield* new ResumeSerializerMismatchError({
        expected: serialization.id,
        actual: manifest.serializer,
        message: `The resume manifest is stamped by serializer "${manifest.serializer}", but this client's Serialization layer is "${serialization.id}".`,
      });
    }
    return manifest;
  }).pipe(Effect.withSpan("Resume.decodeManifest"));
}

/**
 * Restore every named state binding for one component snapshot without
 * executing component setup. Restoration is all-or-nothing: unsupported,
 * missing, unexpected, or invalid bindings fail before client handles are
 * allocated.
 */
/**
 * Live restorations, keyed by manifest identity. A manifest plus a component
 * boundary id names exactly one restorable boundary, and only one restoration
 * of it may be live at a time.
 */
const liveRestorations = new WeakMap<object, Set<ComponentId>>();

function restoreStateBindingsInScope<Props, Req, E, Bindings, Slots>(
  component: Component.Component<Props, Req, E, Bindings, Slots>,
  manifest: Manifest,
  componentIdValue: string,
  propsValue: Props | undefined,
  providedScope?: Scope.Scope,
): Effect.Effect<
  RestoredStateBindings<Bindings, Req>,
  StateBindingRestoreError,
  Req
> {
  return Effect.gen(function* () {
    // A `ValidatedManifest` short-circuits here; anything else crosses the
    // full schema boundary. There is no caller-supplied-identity fast path.
    const validatedManifest = yield* validateManifestValue(
      manifest,
      "state restoration",
    );
    const componentId = yield* Schema.decodeUnknownEffect(ComponentId)(
      componentIdValue,
    ).pipe(
      Effect.catchTag("SchemaError", (error) =>
        Effect.fail(
          new ResumeConfigurationError({
            message: `Invalid resume component ID: ${String(error)}`,
          }),
        ),
      ),
    );
    if (validatedManifest.version === 1) {
      return yield* new ResumeComponentSnapshotNotFoundError({
        componentId,
        message: `Resume manifest v${validatedManifest.version} does not contain component snapshots.`,
      });
    }
    const snapshot = validatedManifest.components[componentId];
    if (snapshot === undefined) {
      return yield* new ResumeComponentSnapshotNotFoundError({
        componentId,
        message: `Resume component snapshot "${componentId}" was not found.`,
      });
    }

    const inspection = Component.inspect(component);
    if (inspection.definition.setupPlan.kind === "opaque") {
      return yield* new ResumeComponentPlanUnsupportedError({
        componentId,
        message: `Component "${componentId}" has opaque setup and requires fallback activation.`,
      });
    }
    const transforms = inspection.definition.transforms;
    const restoresSlots = transforms.some(
      (transform) => transform.kind === "component.withSlots",
    );
    for (const transform of transforms) {
      if (
        transform.kind === "component.withSlots" &&
        transform.portability === "portable"
      ) {
        continue;
      }
      if (
        transform.kind === "component.withBehavior" &&
        transform.portability === "portable" &&
        transform.reattach !== undefined
      ) {
        continue;
      }
      return yield* new ResumeComponentPlanUnsupportedError({
        componentId,
        message: transform.kind === "component.withBehavior"
          ? `Component "${componentId}" contains an opaque behavior attachment and requires fallback activation.`
          : `Component "${componentId}" has a ${transform.phase} transform that cannot be reconstructed during restoration.`,
      });
    }
    const slotContract = restoresSlots
      ? Component.getSlotContract(component)
      : undefined;
    if (
      restoresSlots &&
      (typeof slotContract !== "object" ||
        slotContract === null ||
        !(View.SlotsTypeId in slotContract))
    ) {
      return yield* new ResumeComponentPlanUnsupportedError({
        componentId,
        message: `Component "${componentId}" publishes a portable slot transform without an authored View.Slots contract.`,
      });
    }
    if (
      snapshot.definitionName !== undefined &&
      inspection.definition.name !== undefined &&
      snapshot.definitionName !== inspection.definition.name
    ) {
      return yield* new ResumeComponentPlanUnsupportedError({
        componentId,
        message: `Component "${componentId}" was collected as "${snapshot.definitionName}" but restoration received "${inspection.definition.name}".`,
      });
    }

    const policyResult = statePoliciesFromPlan(
      inspection.definition.setupPlan.steps,
    );
    if (policyResult.unsupportedReason !== undefined) {
      return yield* new ResumeComponentPlanUnsupportedError({
        componentId,
        message: policyResult.unsupportedReason,
      });
    }
    if (policyResult.policies.size === 0) {
      return yield* new ResumeComponentPlanUnsupportedError({
        componentId,
        message: `Component "${componentId}" has no schema-backed state bindings to restore.`,
      });
    }

    for (const name of Object.keys(snapshot.bindings)) {
      if (!policyResult.policies.has(name)) {
        const binding = bindingNameFromValidatedString(name);
        return yield* new ResumeStateBindingUnexpectedError({
          componentId,
          binding,
          message: `Snapshot "${componentId}" contains unexpected binding "${name}".`,
        });
      }
    }

    const decoded: Array<{
      readonly name: BindingName;
      readonly snapshot: BindingSnapshot;
      readonly value: unknown;
      readonly cacheKey?: string;
      readonly reactivityKeys?: ReadonlyArray<string>;
    }> = [];
    for (const [rawName, policy] of policyResult.policies) {
      const name = yield* Schema.decodeUnknownEffect(BindingName)(rawName).pipe(
        Effect.mapError(
          () =>
            new ResumeComponentPlanUnsupportedError({
              componentId,
              message: `Component "${componentId}" declares invalid resumable binding name "${rawName}".`,
            }),
        ),
      );
      const bindingSnapshot = snapshot.bindings[name];
      if (bindingSnapshot === undefined) {
        return yield* new ResumeStateBindingMissingError({
          componentId,
          binding: name,
          message: `Snapshot "${componentId}" is missing binding "${name}".`,
        });
      }
      const expectedKey = `${componentId}/${name}`;
      if (bindingSnapshot.kind !== policy.kind) {
        return yield* new ResumeStateSnapshotDecodeError({
          componentId,
          binding: name,
          message: `Snapshot "${expectedKey}" was collected as a ${bindingSnapshot.kind} binding but the setup plan declares a ${policy.kind} snapshot policy.`,
        });
      }
      if (bindingSnapshot.key !== expectedKey) {
        return yield* new ResumeStateSnapshotDecodeError({
          componentId,
          binding: name,
          message: `Snapshot "${expectedKey}" used unexpected hydration key "${bindingSnapshot.key}".`,
        });
      }
      if (
        bindingSnapshot.kind === "query" &&
        bindingSnapshot.executor.buildId !== validatedManifest.buildId
      ) {
        return yield* new ResumeStateSnapshotDecodeError({
          componentId,
          binding: name,
          message: `Query snapshot "${expectedKey}" references build "${bindingSnapshot.executor.buildId}", not manifest build "${validatedManifest.buildId}".`,
        });
      }
      const value = yield* Schema.decodeUnknownEffect(policy.schema)(
        bindingSnapshot.value,
      ).pipe(
        Effect.catchTag("SchemaError", (error) =>
          Effect.fail(
            new ResumeStateSnapshotDecodeError({
              componentId,
              binding: name,
              message: `Snapshot "${expectedKey}" failed schema decoding: ${String(error)}`,
            }),
          ),
        ),
      );
      const reactivityKeys = bindingSnapshot.kind === "query"
        // DQ-089 derivation exemption: a restored query's key set is
        // library-computed from the manifest and legitimately includes its
        // implicit `af:binding:` key — this is not authored input.
        ? normalizeReactivityKeysDerived(bindingSnapshot.reactivityKeys)
        : undefined;
      const cacheKey = bindingSnapshot.kind === "query"
        ? yield* Effect.try({
            try: () =>
              Portable.cacheKey(bindingSnapshot.executor, reactivityKeys),
            catch: (error) =>
              new ResumeStateSnapshotDecodeError({
                componentId,
                binding: name,
                message: `Query snapshot "${componentId}/${name}" has an invalid cache identity: ${String(error)}`,
              }),
          })
        : undefined;
      decoded.push({
        name,
        snapshot: bindingSnapshot,
        value,
        ...(cacheKey === undefined ? {} : { cacheKey }),
        ...(reactivityKeys === undefined ? {} : { reactivityKeys }),
      });
    }

    const ownsScope = providedScope === undefined;
    const scope = providedScope ?? (yield* Scope.make());
    // One live restoration per (manifest, component boundary). A second
    // restoration would claim the same hydration keys and the same DOM region,
    // so it fails closed instead of silently shadowing the first.
    let liveIds = liveRestorations.get(manifest as object);
    if (liveIds === undefined) {
      liveIds = new Set();
      liveRestorations.set(manifest as object, liveIds);
    }
    if (liveIds.has(componentId)) {
      return yield* new ResumeDuplicateComponentRestorationError({
        componentId,
        message: `Component boundary "${componentId}" already has a live restoration; dispose it before restoring again.`,
      });
    }
    liveIds.add(componentId);
    const claimedIds = liveIds;
    yield* Scope.addFinalizer(
      scope,
      Effect.sync(() => {
        claimedIds.delete(componentId);
      }),
    );
    const registry = Registry.make();
    yield* Scope.addFinalizer(
      scope,
      Effect.sync(() => registry.dispose()),
    );
    const allocate = Effect.gen(function* () {
      const restoredBindings: Record<string, unknown> = {};
      const queries: Record<string, RestoredQueryHandle<Req>> =
        Object.create(null);
      const resolvers: Record<
        string,
        Atom.Writable<unknown, unknown>
      > = Object.create(null);
      const dehydrated: Hydration.DehydratedAtomValue[] = [];
      let disposed = false;
      yield* Scope.addFinalizer(
        scope,
        Effect.sync(() => {
          disposed = true;
        }),
      );

      for (const entry of decoded) {
        if (entry.snapshot.kind === "query") {
          const executor = entry.snapshot.executor;
          const reactivityKeys = entry.reactivityKeys!;
          const bindingName = entry.name;
          const cacheKey = entry.cacheKey!;
          const [readResult, writeResult] = createSignal<
            ResultValue<unknown, unknown>
          >(ResultState.success(entry.value));
          const atom = Atom.derived(() => readResult());
          annotateHandle(atom, {
            kind: "query",
            read: readResult,
            isDisposed: () => disposed,
            reactivityKeys,
          });
          // Coalesce concurrent refreshes the way the expression scheduler
          // does (dirty/requeue): a refresh arriving while one is already in
          // flight marks `dirty` instead of dropping the invalidation, and the
          // owning run performs exactly one trailing rerun once it settles —
          // no matter how many requests arrived mid-flight. This keeps
          // single-flight semantics while never serving stale data.
          let inFlight = false;
          let dirty = false;
          // The state to republish if this run is cancelled: interruption is
          // not a query failure, and leaving the handle `Refreshing` forever
          // is not a settled state either.
          let preRefresh: ResultValue<unknown, unknown> | undefined;
          const runOnce = Effect.gen(function* () {
            const current = readResult();
            preRefresh = current;
            // At runtime `current` is always a settled state here (the owning
            // run only re-enters after writing `fromExit`), but narrow the
            // Loading/Refreshing arms for the type checker regardless.
            if (current._tag !== "Loading") {
              // Risk 4: the Stale unwrap has exactly one definition — the
              // core model's `toRefreshing` — never a hand-derived match.
              writeResult(ResultState.toRefreshing(current));
            }
            const resolved = yield* Portable.resolve(executor).pipe(
              Effect.onError(() =>
                Effect.sync(() => {
                  if (disposed) return;
                  writeResult(current);
                }),
              ),
            );
            const exit = yield* Effect.exit(
              resolved.run() as Effect.Effect<unknown, unknown, Req>,
            );
            if (disposed) return;
            if (Exit.isFailure(exit) && Cause.hasInterrupts(exit.cause)) {
              // Interruption is not a query failure: a cancelled refresh must
              // roll back to the pre-refresh settled state instead of
              // publishing an interrupt cause as data.
              writeResult(current);
              return;
            }
            // `current` is the pre-refresh state, so a failed refresh settles
            // to `Stale` and keeps showing the data the user already has —
            // matching the live query path rather than blanking to `Failure`.
            writeResult(ResultState.fromExitWithPrevious(exit, current));
          }).pipe(
            Effect.onInterrupt(() =>
              Effect.sync(() => {
                // `disposed` is authoritative here: restoration's disposal
                // finalizer runs before refresh fibers are interrupted, so a
                // disposing component is never written to.
                if (disposed) return;
                const previous = preRefresh;
                preRefresh = undefined;
                if (previous !== undefined) writeResult(previous);
              }),
            ),
          );
          const refresh: RestoredQueryHandle<Req>["refresh"] = Effect.gen(
            function* () {
              if (disposed) {
                return yield* new ResumeRestoredQueryDisposedError({
                  componentId,
                  binding: bindingName,
                  message: `Restored query "${componentId}/${bindingName}" was refreshed after its restoration was disposed.`,
                });
              }
              if (inFlight) {
                // A run already owns the executor; requeue exactly one rerun.
                dirty = true;
                return;
              }
              inFlight = true;
              yield* Effect.gen(function* () {
                do {
                  dirty = false;
                  yield* runOnce;
                } while (dirty && !disposed);
              }).pipe(
                Effect.ensuring(
                  Effect.sync(() => {
                    inFlight = false;
                  }),
                ),
              );
            },
          ).pipe(Effect.withSpan("Resume.restoredQueryRefresh"));
          Object.defineProperty(restoredBindings, entry.name, {
            enumerable: true,
            value: atom,
          });
          Object.defineProperty(queries, entry.name, {
            enumerable: true,
            value: {
              cacheKey,
              reactivityKeys,
              refresh,
            },
          });
          continue;
        }
        const atom = yield* Component.state(entry.value);
        Object.defineProperty(restoredBindings, entry.name, {
          enumerable: true,
          value: atom,
        });
        Object.defineProperty(resolvers, entry.snapshot.key, {
          enumerable: true,
          value: atom,
        });
        dehydrated.push({
          "~@effect-atom-jsx/DehydratedAtom": true,
          key: entry.snapshot.key,
          value: entry.value,
          dehydratedAt: entry.snapshot.dehydratedAt,
        });
      }
      yield* Hydration.hydrateEffect(registry, dehydrated, resolvers, {
        mode: "strict",
      }).pipe(
        Effect.catchTags({
          HydrationUnknownKeys: (error) =>
            Effect.fail(
              new ResumeComponentPlanUnsupportedError({
                componentId,
                message: `Restored state contained unknown hydration keys: ${error.keys.join(", ")}.`,
              }),
            ),
          HydrationMissingKeys: (error) =>
            Effect.fail(
              new ResumeComponentPlanUnsupportedError({
                componentId,
                message: `Restored state was missing hydration keys: ${error.keys.join(", ")}.`,
              }),
            ),
        }),
      );

      let committedBindings: unknown = restoredBindings;
      for (const transform of transforms) {
        if (transform.kind === "component.withSlots") {
          // A preceding behavior reattachment may have produced a sealed or
          // frozen bindings object. Publishing slots must then be a classified
          // restoration failure (falling back to activation), never a defect.
          const target = committedBindings as object;
          yield* Effect.try({
            try: () => {
              Object.defineProperty(target, "slots", {
                enumerable: true,
                value: View.Slots.handles(slotContract as View.Slots.Any),
              });
            },
            catch: (error) =>
              new ResumeComponentPlanUnsupportedError({
                componentId,
                message: `Component "${componentId}" could not publish its slot contract onto restored bindings: ${String(error)}`,
              }),
          });
          continue;
        }
        if (transform.kind === "component.withBehavior") {
          committedBindings = yield* transform.reattach!(
            committedBindings,
            propsValue,
          ).pipe(
            Effect.mapError((error) =>
              new ResumePortableBehaviorAttachmentError({
                componentId,
                message: `Portable behavior reattachment failed for component "${componentId}": ${String(error)}`,
              }),
            ),
          );
        }
      }

      return {
        componentId,
        bindings: committedBindings as Bindings,
        queries,
        registry,
        dispose: ownsScope
          ? Effect.suspend(() => Scope.close(scope, Exit.void))
          : Effect.void,
      };
    }).pipe(
      Scope.provide(scope),
      Effect.onError((cause) =>
        ownsScope ? Scope.close(scope, Exit.failCause(cause)) : Effect.void
      ),
    );
    return yield* allocate;
  }).pipe(Effect.withSpan("Resume.restoreStateBindings")) as Effect.Effect<
    RestoredStateBindings<Bindings, Req>,
    StateBindingRestoreError,
    Req
  >;
}

export function restoreStateBindings<Props, Req, E, Bindings, Slots>(
  component: Component.Component<Props, Req, E, Bindings, Slots>,
  manifest: Manifest,
  componentIdValue: string,
  ...[propsValue]: RestorePropsArgs<Props>
): Effect.Effect<
  RestoredStateBindings<Bindings, Req>,
  StateBindingRestoreError,
  Req
> {
  return restoreStateBindingsInScope(
    component,
    manifest,
    componentIdValue,
    propsValue,
  );
}

/**
 * Scoped restoration companion. The restored Registry, handles, and child
 * Scope are released automatically with the caller's Scope.
 */
export function restoreStateBindingsScoped<Props, Req, E, Bindings, Slots>(
  component: Component.Component<Props, Req, E, Bindings, Slots>,
  manifest: Manifest,
  componentIdValue: string,
  ...[propsValue]: RestorePropsArgs<Props>
): Effect.Effect<
  RestoredStateBindings<Bindings, Req>,
  StateBindingRestoreError,
  Scope.Scope | Req
> {
  return Effect.acquireRelease(
    restoreStateBindingsInScope(
      component,
      manifest,
      componentIdValue,
      propsValue,
    ),
    (restored) => restored.dispose,
  ).pipe(Effect.withSpan("Resume.restoreStateBindingsScoped"));
}

const componentBoundaryMarkerPrefix = "af:component:";
const componentBoundaryMarkerPattern = /^af:component:(c[0-9]+):(start|end)$/;
const expressionBoundaryMarkerPrefix = "af:expr:";
const expressionBoundaryMarkerPattern = /^af:expr:(x[0-9]+):(start|end)$/;
export const ExpressionElementMarkerAttribute:
  typeof ExpressionElementMarkerAttributeName =
    ExpressionElementMarkerAttributeName;
const expressionElementMarkerPattern = /^x[0-9]+(?: x[0-9]+)*$/;

/**
 * Drop one instance id from every serialized installation marker, removing the
 * attribute entirely when it was the only id.
 *
 * Used when a fallback-required component loses its durable region after its
 * element targets were already serialized: leaving the id behind would turn a
 * collection warning into an unknown-target installation failure.
 */
function removeExpressionElementMarkerId(
  html: string,
  expressionId: string,
): string {
  return html.replace(
    new RegExp(`\\s${ExpressionElementMarkerAttribute}="([^"]*)"`, "g"),
    (match, ids: string) => {
      const remaining = ids
        .split(" ")
        .filter((id) => id !== expressionId);
      if (remaining.length === ids.split(" ").length) return match;
      return remaining.length === 0
        ? ""
        : ` ${ExpressionElementMarkerAttribute}="${remaining.join(" ")}"`;
    },
  );
}

interface ScannedBoundaryRegion {
  readonly id: string;
  readonly start: Comment;
  readonly end: Comment;
  readonly parentId?: string;
}

type BoundaryRegionScanFailure =
  | {
      readonly kind: "malformed";
      readonly marker: string;
    }
  | {
      readonly kind: "unknown";
      readonly id: string;
    }
  | {
      readonly kind: "duplicate";
      readonly id: string;
      readonly edge: "start" | "end";
    }
  | {
      readonly kind: "nesting";
      readonly id: string;
      readonly expectedId?: string;
    }
  | {
      readonly kind: "missing";
      readonly id: string;
      readonly edge: "start" | "end" | "both";
    };

function scanBoundaryRegions(
  root: Document | Element | ShadowRoot,
  expectedIds: ReadonlySet<string>,
  markerPrefix: string,
  markerPattern: RegExp,
):
  | {
      readonly ok: true;
      readonly regions: ReadonlyMap<string, ScannedBoundaryRegion>;
    }
  | {
      readonly ok: false;
      readonly failure: BoundaryRegionScanFailure;
    }
{
  const starts = new Map<string, Comment>();
  const ends = new Map<string, Comment>();
  const parents = new Map<string, string>();
  const open: string[] = [];

  for (const node of nodesInDocumentOrder(root)) {
    const marker = componentBoundaryComment(node);
    if (marker === undefined || !marker.startsWith(markerPrefix)) continue;
    const match = markerPattern.exec(marker);
    if (match === null || match[1] === undefined || match[2] === undefined) {
      return {
        ok: false,
        failure: { kind: "malformed", marker },
      };
    }
    const id = match[1];
    const edge = match[2] as "start" | "end";
    if (!expectedIds.has(id)) {
      return {
        ok: false,
        failure: { kind: "unknown", id },
      };
    }
    if (edge === "start") {
      if (starts.has(id)) {
        return {
          ok: false,
          failure: { kind: "duplicate", id, edge },
        };
      }
      starts.set(id, node as Comment);
      const parentId = open.at(-1);
      if (parentId !== undefined) parents.set(id, parentId);
      open.push(id);
      continue;
    }
    if (ends.has(id)) {
      return {
        ok: false,
        failure: { kind: "duplicate", id, edge },
      };
    }
    const expectedId = open.at(-1);
    if (expectedId !== id) {
      return {
        ok: false,
        failure: {
          kind: "nesting",
          id,
          ...(expectedId === undefined ? {} : { expectedId }),
        },
      };
    }
    open.pop();
    ends.set(id, node as Comment);
  }

  const regions = new Map<string, ScannedBoundaryRegion>();
  for (const id of expectedIds) {
    const start = starts.get(id);
    const end = ends.get(id);
    if (start === undefined || end === undefined) {
      return {
        ok: false,
        failure: {
          kind: "missing",
          id,
          edge: start === undefined && end === undefined
            ? "both"
            : start === undefined
              ? "start"
              : "end",
        },
      };
    }
    regions.set(id, {
      id,
      start,
      end,
      ...(parents.get(id) === undefined
        ? {}
        : { parentId: parents.get(id) }),
    });
  }
  return { ok: true, regions };
}

/**
 * Discover and validate document-local component ownership regions.
 *
 * Regions are returned in manifest order after marker identity, uniqueness,
 * completeness, and proper nesting have all been checked.
 */
export function scanComponentBoundaries(
  root: Document | Element | ShadowRoot,
  manifestValue: Manifest,
): Effect.Effect<
  ReadonlyMap<ComponentId, ComponentBoundary>,
  ComponentBoundaryScanError
> {
  return Effect.gen(function* () {
    const manifest = yield* validateManifestValue(
      manifestValue,
      "component boundary discovery",
    );
    const components = manifest.version === 1 ? {} : manifest.components;
    const expectedIds = new Set(Object.keys(components));
    const scanned = scanBoundaryRegions(
      root,
      expectedIds,
      componentBoundaryMarkerPrefix,
      componentBoundaryMarkerPattern,
    );
    if (!scanned.ok) {
      const failure = scanned.failure;
      if (failure.kind === "malformed") {
        return yield* new ResumeInvalidComponentBoundaryMarkerError({
          marker: failure.marker,
          message: `Component boundary marker "${failure.marker}" is malformed.`,
        });
      }
      const componentId = componentIdFromValidatedString(failure.id);
      if (failure.kind === "unknown") {
        return yield* new ResumeUnknownComponentBoundaryError({
          componentId,
          message: `Component boundary "${componentId}" has no matching manifest record.`,
        });
      }
      if (failure.kind === "duplicate") {
        return yield* new ResumeDuplicateComponentBoundaryError({
          componentId,
          edge: failure.edge,
          message: `Component boundary "${componentId}" has more than one ${failure.edge} marker.`,
        });
      }
      if (failure.kind === "nesting") {
        return yield* new ResumeComponentBoundaryNestingError({
          componentId,
          ...(failure.expectedId === undefined
            ? {}
            : {
                expectedComponentId:
                  componentIdFromValidatedString(failure.expectedId),
              }),
          message: failure.expectedId === undefined
            ? `Component boundary "${componentId}" ended without a matching open region.`
            : `Component boundary "${componentId}" crossed the open "${failure.expectedId}" region.`,
        });
      }
      return yield* new ResumeMissingComponentBoundaryError({
        componentId,
        edge: failure.edge,
        message: `Component boundary "${componentId}" is missing its ${failure.edge} marker${
          failure.edge === "both" ? "s" : ""
        }.`,
      });
    }
    const boundaries = new Map<ComponentId, ComponentBoundary>();
    for (const region of scanned.regions.values()) {
      const componentId = componentIdFromValidatedString(region.id);
      boundaries.set(componentId, {
        componentId,
        start: region.start,
        end: region.end,
        ...(region.parentId === undefined
          ? {}
          : {
              parentComponentId: componentIdFromValidatedString(
                region.parentId,
              ),
            }),
      });
    }
    return boundaries;
  }).pipe(Effect.withSpan("Resume.scanComponentBoundaries"));
}

/**
 * Discover and validate document-local fine-grained expression regions.
 */
export function scanExpressionBoundaries(
  root: Document | Element | ShadowRoot,
  manifestValue: Manifest,
): Effect.Effect<
  ReadonlyMap<ExpressionId, ExpressionBoundary>,
  ExpressionBoundaryScanError
> {
  return Effect.gen(function* () {
    const manifest = yield* validateManifestValue(
      manifestValue,
      "expression boundary discovery",
    );
    const expressions = expressionEntriesOf(manifest);
    // Text and structural targets share the comment-pair region shape, so both
    // are legitimate boundary owners here.
    const boundaryExpressionIds = new Set<ExpressionId>();
    for (const [expressionId, entry] of Object.entries(expressions) as Array<
      [ExpressionId, ExpressionEntry]
    >) {
      const kind = expressionTargetOf(entry).kind;
      if (kind === "text" || kind === "structural") {
        boundaryExpressionIds.add(expressionId);
      }
    }
    const scanned = scanBoundaryRegions(
      root,
      boundaryExpressionIds,
      expressionBoundaryMarkerPrefix,
      expressionBoundaryMarkerPattern,
    );
    if (!scanned.ok) {
      const failure = scanned.failure;
      if (failure.kind === "malformed") {
        return yield* new ResumeInvalidExpressionBoundaryMarkerError({
          marker: failure.marker,
          message: `Expression boundary marker "${failure.marker}" is malformed.`,
        });
      }
      const expressionId = expressionIdFromValidatedString(failure.id);
      if (failure.kind === "unknown") {
        return yield* new ResumeUnknownExpressionBoundaryError({
          expressionId,
          message: `Expression boundary "${expressionId}" has no matching manifest record.`,
        });
      }
      if (failure.kind === "duplicate") {
        return yield* new ResumeDuplicateExpressionBoundaryError({
          expressionId,
          edge: failure.edge,
          message: `Expression boundary "${expressionId}" has more than one ${failure.edge} marker.`,
        });
      }
      if (failure.kind === "nesting") {
        return yield* new ResumeExpressionBoundaryNestingError({
          expressionId,
          ...(failure.expectedId === undefined
            ? {}
            : {
                expectedExpressionId:
                  expressionIdFromValidatedString(failure.expectedId),
              }),
          message: failure.expectedId === undefined
            ? `Expression boundary "${expressionId}" ended without a matching open region.`
            : `Expression boundary "${expressionId}" crossed the open "${failure.expectedId}" region.`,
        });
      }
      return yield* new ResumeMissingExpressionBoundaryError({
        expressionId,
        edge: failure.edge,
        message: `Expression boundary "${expressionId}" is missing its ${failure.edge} marker${
          failure.edge === "both" ? "s" : ""
        }.`,
      });
    }

    const boundaries = new Map<ExpressionId, ExpressionBoundary>();
    for (const region of scanned.regions.values()) {
      const expressionId = expressionIdFromValidatedString(region.id);
      boundaries.set(expressionId, {
        expressionId,
        start: region.start,
        end: region.end,
        ...(region.parentId === undefined
          ? {}
          : {
              parentExpressionId:
                expressionIdFromValidatedString(region.parentId),
            }),
      });
    }
    return boundaries;
  }).pipe(Effect.withSpan("Resume.scanExpressionBoundaries"));
}

/**
 * Discover every v3/v4 expression target in one expression-marker traversal.
 *
 * Element markers contain only document-local expression IDs; target kind and
 * target names remain schema-validated manifest metadata. Markers are removed
 * only after the complete manifest/DOM bijection succeeds, so a failed scan
 * leaves the SSR document available for activation fallback or diagnostics.
 * Component-boundary discovery is a separate traversal unless the internal
 * installation coordinator has already supplied its validated boundary map.
 */
function scanExpressionTargetsWithComponentBoundaries(
  root: Document | Element | ShadowRoot,
  manifestValue: Manifest,
  componentBoundaries?: ReadonlyMap<ComponentId, ComponentBoundary>,
): Effect.Effect<
  ReadonlyMap<ExpressionId, ScannedExpressionTarget>,
  ExpressionTargetScanError
> {
  return Effect.gen(function* () {
    const manifest = yield* validateManifestValue(
      manifestValue,
      "expression target discovery",
    );
    const entries = expressionEntriesOf(manifest);
    const starts = new Map<ExpressionId, Comment>();
    const ends = new Map<ExpressionId, Comment>();
    const parents = new Map<ExpressionId, ExpressionId>();
    const open: ExpressionId[] = [];
    const elementTargets = new Map<ExpressionId, Element>();
    const markedElements = new Map<Element, string>();

    for (const node of nodesInDocumentOrderIncludingRoot(root)) {
      const comment = componentBoundaryComment(node);
      if (
        comment !== undefined
        && comment.startsWith(expressionBoundaryMarkerPrefix)
      ) {
        const match = expressionBoundaryMarkerPattern.exec(comment);
        if (
          match === null
          || match[1] === undefined
          || match[2] === undefined
        ) {
          return yield* new ResumeInvalidExpressionBoundaryMarkerError({
            marker: comment,
            message: `Expression boundary marker "${comment}" is malformed.`,
          });
        }
        const expressionId =
          expressionIdFromValidatedString(match[1]);
        const entry = entries[expressionId];
        if (entry === undefined) {
          return yield* new ResumeUnknownExpressionBoundaryError({
            expressionId,
            message: `Expression boundary "${expressionId}" has no matching manifest record.`,
          });
        }
        const declaredKind = expressionTargetOf(entry).kind;
        if (declaredKind !== "text" && declaredKind !== "structural") {
          return yield* new ResumeExpressionTargetKindMismatchError({
            expressionId,
            expected: "element",
            actual: "text",
            message: `Expression "${expressionId}" is declared as an element target but was marked with a comment-pair boundary.`,
          });
        }
        const edge = match[2] as "start" | "end";
        if (edge === "start") {
          if (starts.has(expressionId)) {
            return yield* new ResumeDuplicateExpressionBoundaryError({
              expressionId,
              edge,
              message: `Expression boundary "${expressionId}" has more than one start marker.`,
            });
          }
          starts.set(expressionId, node as Comment);
          const parentExpressionId = open.at(-1);
          if (parentExpressionId !== undefined) {
            parents.set(expressionId, parentExpressionId);
          }
          open.push(expressionId);
        } else {
          if (ends.has(expressionId)) {
            return yield* new ResumeDuplicateExpressionBoundaryError({
              expressionId,
              edge,
              message: `Expression boundary "${expressionId}" has more than one end marker.`,
            });
          }
          const expectedExpressionId = open.at(-1);
          if (expectedExpressionId !== expressionId) {
            return yield* new ResumeExpressionBoundaryNestingError({
              expressionId,
              ...(expectedExpressionId === undefined
                ? {}
                : { expectedExpressionId }),
              message: expectedExpressionId === undefined
                ? `Expression boundary "${expressionId}" ended without a matching open region.`
                : `Expression boundary "${expressionId}" crossed the open "${expectedExpressionId}" region.`,
            });
          }
          open.pop();
          ends.set(expressionId, node as Comment);
        }
      }

      if (typeof node !== "object" || node === null) continue;
      const element = node as Partial<Element>;
      if (typeof element.getAttribute !== "function") continue;
      const marker = element.getAttribute(ExpressionElementMarkerAttribute);
      if (marker === null) continue;
      if (!expressionElementMarkerPattern.test(marker)) {
        return yield* new ResumeInvalidExpressionElementMarkerError({
          marker,
          message: `Expression element marker "${marker}" must be a space-separated list of canonical expression IDs.`,
        });
      }
      const targetElement = node as Element;
      markedElements.set(targetElement, marker);
      for (const rawExpressionId of marker.split(" ")) {
        const expressionId =
          expressionIdFromValidatedString(rawExpressionId);
        const entry = entries[expressionId];
        if (entry === undefined) {
          return yield* new ResumeUnknownExpressionElementTargetError({
            expressionId,
            message: `Expression element target "${expressionId}" has no matching manifest record.`,
          });
        }
        const declaredElementKind = expressionTargetOf(entry).kind;
        if (
          declaredElementKind === "text" || declaredElementKind === "structural"
        ) {
          return yield* new ResumeExpressionTargetKindMismatchError({
            expressionId,
            expected: declaredElementKind,
            actual: "element",
            message: `Expression "${expressionId}" is declared as a ${declaredElementKind} target but was marked on an element.`,
          });
        }
        if (elementTargets.has(expressionId)) {
          return yield* new ResumeDuplicateExpressionElementTargetError({
            expressionId,
            message: `Expression element target "${expressionId}" is marked more than once.`,
          });
        }
        elementTargets.set(expressionId, targetElement);
      }
    }

    const targets = new Map<ExpressionId, ScannedExpressionTarget>();
    for (const [expressionId, entry] of Object.entries(entries) as Array<
      [ExpressionId, ExpressionEntry]
    >) {
      const target = expressionTargetOf(entry);
      if (target.kind === "text" || target.kind === "structural") {
        const start = starts.get(expressionId);
        const end = ends.get(expressionId);
        if (start === undefined || end === undefined) {
          return yield* new ResumeMissingExpressionBoundaryError({
            expressionId,
            edge: start === undefined && end === undefined
              ? "both"
              : start === undefined
                ? "start"
                : "end",
            message: `Expression boundary "${expressionId}" is incomplete.`,
          });
        }
        const boundary: ExpressionBoundary = {
          expressionId,
          start,
          end,
          ...(parents.get(expressionId) === undefined
            ? {}
            : { parentExpressionId: parents.get(expressionId) }),
        };
        targets.set(
          expressionId,
          target.kind === "text"
            ? { kind: "text", expressionId, boundary }
            : {
                kind: "structural",
                expressionId,
                boundary,
                mode: target.mode,
              },
        );
        continue;
      }

      const element = elementTargets.get(expressionId);
      if (element === undefined) {
        return yield* new ResumeMissingExpressionElementTargetError({
          expressionId,
          message: `Expression element target "${expressionId}" is missing its "${ExpressionElementMarkerAttribute}" marker.`,
        });
      }
      switch (target.kind) {
        case "attribute":
          targets.set(expressionId, {
            kind: "attribute",
            expressionId,
            element,
            name: target.name,
          });
          break;
        case "class":
          targets.set(expressionId, {
            kind: "class",
            expressionId,
            element,
          });
          break;
        case "style-property":
          targets.set(expressionId, {
            kind: "style-property",
            expressionId,
            element,
            name: target.name,
          });
          break;
      }
    }

    const boundaries = componentBoundaries
      ?? (yield* scanComponentBoundaries(root, manifest));
    yield* validateScannedExpressionOwnership(
      boundaries,
      targets,
      entries,
    );

    const removedMarkers: Array<readonly [Element, string]> = [];
    for (const [element, marker] of markedElements) {
      const removal = yield* Effect.exit(
        Effect.try(() =>
          element.removeAttribute(ExpressionElementMarkerAttribute)
        ),
      );
      if (Exit.isSuccess(removal)) {
        removedMarkers.push([element, marker]);
        continue;
      }
      const rollbackExits = yield* Effect.forEach(
        removedMarkers,
        ([removed, removedMarker]) =>
          Effect.exit(
            Effect.try(() =>
              removed.setAttribute(
                ExpressionElementMarkerAttribute,
                removedMarker,
              )
            ),
          ),
      );
      const rollbackFailures = rollbackExits.flatMap((rollback) =>
        Exit.isFailure(rollback) ? [Cause.pretty(rollback.cause)] : []
      );
      return yield* new ResumeExpressionElementMarkerCleanupError({
        message:
          `Expression element marker cleanup failed: ${Cause.pretty(removal.cause)}${
            rollbackFailures.length === 0
              ? ""
              : `; marker rollback also failed: ${rollbackFailures.join("; ")}`
          }`,
      });
    }
    return targets;
  }).pipe(Effect.withSpan("Resume.scanExpressionTargets"));
}

export function scanExpressionTargets(
  root: Document | Element | ShadowRoot,
  manifestValue: Manifest,
): Effect.Effect<
  ReadonlyMap<ExpressionId, ScannedExpressionTarget>,
  ExpressionTargetScanError
> {
  return scanExpressionTargetsWithComponentBoundaries(
    root,
    manifestValue,
  );
}

function boundaryRegionTarget(
  boundary: {
    readonly start: Comment;
    readonly end: Comment;
  },
  label: string,
): Element {
  const parent = boundary.start.parentNode;
  if (parent === null || boundary.end.parentNode !== parent) {
    throw new Error(
      `${label} is no longer attached to one parent.`,
    );
  }

  const nodes = (): Node[] => {
    const found: Node[] = [];
    let current = boundary.start.nextSibling;
    while (current !== null && current !== boundary.end) {
      found.push(current);
      current = current.nextSibling;
    }
    if (current !== boundary.end) {
      throw new Error(
        `${label} is no longer contiguous.`,
      );
    }
    return found;
  };
  const requireOwned = (node: Node): void => {
    if (!nodes().includes(node)) {
      throw new Error(
        `Node is outside ${label}.`,
      );
    }
  };

  return {
    get firstChild(): ChildNode | null {
      return (nodes()[0] as ChildNode | undefined) ?? null;
    },
    get childNodes(): NodeListOf<ChildNode> {
      return nodes() as unknown as NodeListOf<ChildNode>;
    },
    appendChild<T extends Node>(node: T): T {
      return parent.insertBefore(node, boundary.end);
    },
    insertBefore<T extends Node>(node: T, child: Node | null): T {
      if (child !== null) requireOwned(child);
      return parent.insertBefore(node, child ?? boundary.end);
    },
    removeChild<T extends Node>(child: T): T {
      requireOwned(child);
      return parent.removeChild(child) as T;
    },
    replaceChild<T extends Node>(node: Node, child: T): T {
      requireOwned(child);
      return parent.replaceChild(node, child) as T;
    },
  } as unknown as Element;
}

function componentBoundaryTarget(boundary: ComponentBoundary): Element {
  return boundaryRegionTarget(
    boundary,
    `Component boundary "${boundary.componentId}"`,
  );
}

function patchExpressionBoundary(
  boundary: ExpressionBoundary,
  value: string | number,
): void {
  const parent = boundary.start.parentNode;
  if (parent === null || boundary.end.parentNode !== parent) {
    throw new Error(
      `Expression boundary "${boundary.expressionId}" is no longer attached to one parent.`,
    );
  }
  const text = String(value);
  const first = boundary.start.nextSibling;
  if (
    first !== null
    && first !== boundary.end
    && first.nodeName === "#text"
    && first.nextSibling === boundary.end
  ) {
    first.textContent = text;
    return;
  }
  let current = first;
  while (current !== null && current !== boundary.end) {
    const next = current.nextSibling;
    parent.removeChild(current);
    current = next;
  }
  if (current !== boundary.end) {
    throw new Error(
      `Expression boundary "${boundary.expressionId}" is no longer contiguous.`,
    );
  }
  const ownerDocument =
    boundary.start.ownerDocument
    ?? (globalThis as { readonly document?: Document }).document;
  if (ownerDocument === undefined) {
    throw new Error(
      `Expression boundary "${boundary.expressionId}" has no document for text patching.`,
    );
  }
  parent.insertBefore(ownerDocument.createTextNode(text), boundary.end);
}

/**
 * Whether a computed value may reach a target's patch strategy.
 *
 * Element targets accept the full authored `ExpressionOutput`, where `null` and
 * `undefined` mean removal. A durable text region has no representation for
 * absence, so it still accepts only `string | number`.
 */
function isSupportedExpressionOutput(
  target: Exclude<ScannedExpressionTarget, { kind: "structural" }>,
  value: unknown,
): value is ExpressionOutput {
  if (typeof value === "string" || typeof value === "number") return true;
  return target.kind !== "text" && (value === null || value === undefined);
}

/**
 * Apply one computed expression value to its discriminated target.
 *
 * Element targets delegate to the ordinary `dom.ts` helpers, so nullish removal
 * and string coercion cannot drift from the ordinary rendering path.
 * Ownership is rechecked immediately before the write: an element that left the
 * document, or left the component region the manifest assigned it to, is a
 * classified patch failure rather than a silent mutation.
 */
function patchExpressionTarget(
  target: Exclude<ScannedExpressionTarget, { kind: "structural" }>,
  value: ExpressionOutput,
  ownerBoundary: ComponentBoundary | undefined,
): void {
  if (target.kind === "text") {
    patchExpressionBoundary(
      target.boundary,
      value as string | number,
    );
    return;
  }
  const element = target.element;
  const attached = ownerBoundary === undefined
    ? (element as { readonly parentNode?: Node | null }).parentNode != null
    : componentBoundaryContains(ownerBoundary, element);
  if (!attached) {
    throw new Error(
      `Expression element target "${target.expressionId}" no longer belongs to the document region it was installed against.`,
    );
  }
  switch (target.kind) {
    case "attribute":
      domSetAttribute(element, target.name, value);
      return;
    case "class":
      domClassName(element, value);
      return;
    case "style-property":
      domSetStyleProperty(element as HTMLElement, target.name, value);
      return;
  }
}

/**
 * Milestone 8d structural regions (`DQ-100`).
 *
 * A structural region lives between the ordinary `af:expr` markers and holds
 * one `Map<key, row>`; each row owns a child `Scope` opened when the row
 * appears and closed exactly when the reconciler drops it. Disposal is driven
 * from the same key diff that produces the reconciler's removals, so "dropped
 * from the DOM" and "Scope closed" derive from one list rather than being kept
 * in agreement by convention.
 */
const structuralRowMarkerPattern = /^af:row:(x[0-9]+):([^:]*):(s|e)$/;

type StructuralRowScope = ReturnType<typeof Scope.makeUnsafe>;

interface StructuralRowInstance {
  readonly key: string;
  readonly scope: StructuralRowScope;
  nodes: Node[];
}

interface StructuralRegionState {
  readonly rows: Map<string, StructuralRowInstance>;
  order: string[];
}

export interface StructuralRowScopeObservation {
  readonly expressionId: ExpressionId;
  readonly key: string;
  readonly scope: StructuralRowScope;
}

const structuralRowScopeObservers = new Set<
  (observation: StructuralRowScopeObservation) => void
>();

/**
 * Observe every structural row `Scope` as it opens, so tests can register
 * finalizers and count their runs at the moment of removal — final-state
 * inspection would pass for an implementation that deferred every row's
 * cleanup to unmount, which is precisely the leak `DQ-100` exists to prevent.
 *
 * @internal
 */
export function onStructuralRowScopeOpened(
  observer: (observation: StructuralRowScopeObservation) => void,
): () => void {
  structuralRowScopeObservers.add(observer);
  return () => {
    structuralRowScopeObservers.delete(observer);
  };
}

function openStructuralRowScope(
  expressionId: ExpressionId,
  key: string,
): StructuralRowScope {
  const scope = Scope.makeUnsafe();
  for (const observer of structuralRowScopeObservers) {
    try {
      observer({ expressionId, key, scope });
    } catch {
      // Observability callbacks must never compromise patching or cleanup.
    }
  }
  return scope;
}

/**
 * Recover `Map<key, nodes>` from the SSR document's `af:row` marker pairs.
 * Runs once, on the region's first invalidation; later patches evolve the
 * in-memory state instead of re-scanning.
 */
function recoverStructuralRegionState(
  target: Extract<ScannedExpressionTarget, { kind: "structural" }>,
): StructuralRegionState {
  const boundary = target.boundary;
  const parent = boundary.start.parentNode;
  if (parent === null || boundary.end.parentNode !== parent) {
    throw new Error(
      `Structural region "${target.expressionId}" is no longer contiguous.`,
    );
  }
  const rows = new Map<string, StructuralRowInstance>();
  const order: string[] = [];
  let openRow: { readonly key: string; readonly nodes: Node[] } | undefined;
  let current: Node | null = boundary.start.nextSibling;
  while (current !== null && current !== boundary.end) {
    const comment = componentBoundaryComment(current);
    const match = comment === undefined
      ? null
      : structuralRowMarkerPattern.exec(comment);
    if (
      match !== null
      && match[1] === target.expressionId
      && match[2] !== undefined
    ) {
      const key = decodeStructuralRowKey(match[2]);
      if (match[3] === "s") {
        if (openRow !== undefined) {
          throw new Error(
            `Structural region "${target.expressionId}" row "${openRow.key}" is missing its end marker.`,
          );
        }
        openRow = { key, nodes: [current] };
      } else {
        if (openRow === undefined || openRow.key !== key) {
          throw new Error(
            `Structural region "${target.expressionId}" row "${key}" has an unmatched end marker.`,
          );
        }
        if (rows.has(key)) {
          throw new Error(
            `Structural region "${target.expressionId}" row key "${key}" appears more than once.`,
          );
        }
        openRow.nodes.push(current);
        rows.set(key, {
          key,
          scope: openStructuralRowScope(target.expressionId, key),
          nodes: openRow.nodes,
        });
        order.push(key);
        openRow = undefined;
      }
    } else if (openRow !== undefined) {
      openRow.nodes.push(current);
    }
    current = current.nextSibling;
  }
  if (openRow !== undefined) {
    throw new Error(
      `Structural region "${target.expressionId}" row "${openRow.key}" is missing its end marker.`,
    );
  }
  if (current !== boundary.end) {
    throw new Error(
      `Structural region "${target.expressionId}" is no longer contiguous.`,
    );
  }
  return { rows, order };
}

function updateStructuralRowText(
  instance: StructuralRowInstance,
  text: string | number,
  parent: Node,
  ownerDocument: Document,
): void {
  const value = String(text);
  const start = instance.nodes[0]!;
  const end = instance.nodes[instance.nodes.length - 1]!;
  const content = instance.nodes.slice(1, -1);
  if (content.length === 1 && content[0]!.nodeName === "#text") {
    if (content[0]!.textContent !== value) {
      content[0]!.textContent = value;
    }
    return;
  }
  for (const node of content) {
    if (node.parentNode === parent) parent.removeChild(node);
  }
  const textNode = ownerDocument.createTextNode(value);
  parent.insertBefore(textNode, end);
  instance.nodes = [start, textNode, end];
}

/**
 * Reconcile one structural region against freshly computed rows.
 *
 * Surviving rows keep node identity; their text is updated in place. The key
 * diff that removes DOM rows is the same one whose dropped keys' Scopes the
 * caller closes — the returned `removedScopes` list is that single source.
 */
function patchStructuralExpressionTarget(
  target: Extract<ScannedExpressionTarget, { kind: "structural" }>,
  previous: StructuralRegionState | undefined,
  rows: ReadonlyArray<StructuralRow>,
  ownerBoundary: ComponentBoundary | undefined,
): {
  readonly state: StructuralRegionState;
  readonly removedScopes: ReadonlyArray<StructuralRowScope>;
} {
  const boundary = target.boundary;
  if (
    ownerBoundary !== undefined
    && !(
      componentBoundaryContains(ownerBoundary, boundary.start)
      && componentBoundaryContains(ownerBoundary, boundary.end)
    )
  ) {
    throw new Error(
      `Structural region "${target.expressionId}" no longer belongs to the document region it was installed against.`,
    );
  }
  const parent = boundary.start.parentNode;
  if (parent === null || boundary.end.parentNode !== parent) {
    throw new Error(
      `Structural region "${target.expressionId}" is no longer contiguous.`,
    );
  }
  const ownerDocument =
    boundary.start.ownerDocument
    ?? (globalThis as { readonly document?: Document }).document;
  if (ownerDocument === undefined) {
    throw new Error(
      `Structural region "${target.expressionId}" has no document for patching.`,
    );
  }
  const state = previous ?? recoverStructuralRegionState(target);
  const oldNodes = state.order.flatMap(
    (key) => state.rows.get(key)?.nodes ?? [],
  );
  const newNodes: Node[] = [];
  const newOrder: string[] = [];
  for (const row of rows) {
    let instance = state.rows.get(row.key);
    if (instance === undefined) {
      const encodedKey = encodeStructuralRowKey(row.key);
      instance = {
        key: row.key,
        scope: openStructuralRowScope(target.expressionId, row.key),
        nodes: [
          ownerDocument.createComment(
            `af:row:${target.expressionId}:${encodedKey}:s`,
          ),
          ownerDocument.createTextNode(String(row.text)),
          ownerDocument.createComment(
            `af:row:${target.expressionId}:${encodedKey}:e`,
          ),
        ],
      };
      state.rows.set(row.key, instance);
    } else {
      updateStructuralRowText(instance, row.text, parent, ownerDocument);
    }
    newOrder.push(row.key);
    newNodes.push(...instance.nodes);
  }
  const survivingKeys = new Set(newOrder);
  const removedScopes: StructuralRowScope[] = [];
  for (const key of state.order) {
    if (survivingKeys.has(key)) continue;
    const dropped = state.rows.get(key);
    if (dropped === undefined) continue;
    removedScopes.push(dropped.scope);
    state.rows.delete(key);
  }
  domReconcileArrays(
    parent as Element,
    oldNodes,
    newNodes,
    boundary.end,
  );
  state.order = newOrder;
  return { state, removedScopes };
}

function componentBoundaryContains(
  boundary: ComponentBoundary,
  candidate: EventTarget,
): boolean {
  const parent = boundary.start.parentNode;
  if (parent === null || boundary.end.parentNode !== parent) return false;
  let current = candidate as (EventTarget & { readonly parentNode?: Node | null });
  while (current.parentNode !== parent) {
    if (current.parentNode === undefined || current.parentNode === null) {
      return false;
    }
    current = current.parentNode;
  }
  let sibling = boundary.start.nextSibling;
  while (sibling !== null && sibling !== boundary.end) {
    if (sibling === current) return true;
    sibling = sibling.nextSibling;
  }
  return false;
}

function validateExpressionOwnership(
  componentBoundaries: ReadonlyMap<ComponentId, ComponentBoundary>,
  expressionBoundaries: ReadonlyMap<ExpressionId, ExpressionBoundary>,
  entries: Readonly<Record<ExpressionId, ExpressionEntry>>,
): Effect.Effect<void, ResumeExpressionOwnershipError> {
  const targets = new Map<ExpressionId, ScannedExpressionTarget>();
  for (const [expressionId, boundary] of expressionBoundaries) {
    targets.set(expressionId, {
      kind: "text",
      expressionId,
      boundary,
    });
  }
  return validateScannedExpressionOwnership(
    componentBoundaries,
    targets,
    entries,
  );
}

function validateScannedExpressionOwnership(
  componentBoundaries: ReadonlyMap<ComponentId, ComponentBoundary>,
  targets: ReadonlyMap<ExpressionId, ScannedExpressionTarget>,
  entries: Readonly<Record<ExpressionId, ExpressionEntry>>,
): Effect.Effect<void, ResumeExpressionOwnershipError> {
  const depths = new Map<ComponentId, number>();
  const depth = (boundary: ComponentBoundary): number => {
    const cached = depths.get(boundary.componentId);
    if (cached !== undefined) return cached;
    let value = 0;
    let parentId = boundary.parentComponentId;
    while (parentId !== undefined) {
      value += 1;
      parentId = componentBoundaries.get(parentId)?.parentComponentId;
    }
    depths.set(boundary.componentId, value);
    return value;
  };
  return Effect.gen(function* () {
    for (const [expressionId, entry] of Object.entries(entries) as Array<
      [ExpressionId, ExpressionEntry]
    >) {
      const target = targets.get(expressionId);
      if (target === undefined) continue;
      let closest: ComponentBoundary | undefined;
      let closestDepth = -1;
      for (const boundary of componentBoundaries.values()) {
        const contains =
          target.kind === "text" || target.kind === "structural"
            ? componentBoundaryContains(boundary, target.boundary.start)
              && componentBoundaryContains(boundary, target.boundary.end)
            : componentBoundaryContains(boundary, target.element);
        if (!contains) continue;
        const boundaryDepth = depth(boundary);
        if (boundaryDepth > closestDepth) {
          closest = boundary;
          closestDepth = boundaryDepth;
        }
      }
      if (entry.component === undefined) {
        if (closest === undefined) continue;
        return yield* new ResumeExpressionOwnershipError({
          expressionId,
          componentId: closest.componentId,
          message: `Expression target "${expressionId}" is inside component "${closest.componentId}" but has no manifest owner.`,
        });
      }
      if (
        closest === undefined
        || closest.componentId !== entry.component
      ) {
        return yield* new ResumeExpressionOwnershipError({
          expressionId,
          componentId: entry.component,
          message: closest === undefined
            ? `Expression target "${expressionId}" is not contained by its manifest component "${entry.component}".`
            : `Expression target "${expressionId}" belongs to closest component "${closest.componentId}", not manifest component "${entry.component}".`,
        });
      }
    }
  });
}

function validateExpressionDependencyMetadata(
  entries: Readonly<Record<ExpressionId, ExpressionEntry>>,
): Effect.Effect<void, ResumeExpressionDependencyMetadataError> {
  return Effect.gen(function* () {
    for (const [expressionId, entry] of Object.entries(entries) as Array<
      [ExpressionId, ExpressionEntry]
    >) {
      const declared = new Set<string>();
      for (const key of entry.deps) {
        if (key.length === 0) {
          return yield* new ResumeExpressionDependencyMetadataError({
            expressionId,
            message: `Expression "${expressionId}" declares an empty reactivity key.`,
          });
        }
        if (declared.has(key)) {
          return yield* new ResumeExpressionDependencyMetadataError({
            expressionId,
            message: `Expression "${expressionId}" declares duplicate reactivity key "${key}".`,
          });
        }
        declared.add(key);
      }
      for (const key of entry.inputs ?? []) {
        if (!declared.has(key)) {
          return yield* new ResumeExpressionDependencyMetadataError({
            expressionId,
            message: `Expression "${expressionId}" input key "${key}" is not one of its declared invalidation dependencies.`,
          });
        }
      }
    }
  });
}

function manifestWithBindingOverrides(
  manifest: ValidatedManifest,
  componentId: ComponentId,
  overrides: ReadonlyMap<
    ComponentId,
    ReadonlyMap<BindingName, unknown>
  >,
): ValidatedManifest {
  if (manifest.version === 1 || overrides.size === 0) return manifest;
  const componentOverrides = overrides.get(componentId);
  const component = manifest.components[componentId];
  if (componentOverrides === undefined || component === undefined) {
    return manifest;
  }
  const bindings: Record<BindingName, BindingSnapshot> = {
    ...component.bindings,
  };
  for (const [binding, value] of componentOverrides) {
    const snapshot = bindings[binding];
    if (snapshot !== undefined) {
      bindings[binding] = {
        ...snapshot,
        value,
      };
    }
  }
  // Library-derived from an already-validated manifest, so it inherits the
  // brand without re-decoding. It is deliberately *not* deep-frozen: the
  // override values are live client state, not wire data, and this view never
  // escapes restoration for `componentId`.
  return brandManifest({
    ...manifest,
    // This internal view is consumed only by restoration for `componentId`.
    // Keeping a one-component record avoids cloning every boundary whenever a
    // dormant write has overridden one snapshot.
    components: {
      [componentId]: {
        ...component,
        bindings,
      },
    },
  });
}

function findBoundaryReplayTarget(
  root: Document | Element | ShadowRoot,
  boundary: ComponentBoundary,
  eventType: EventType,
  targetKey: EventTargetKey,
): Element | undefined {
  const attribute = replayTargetAttribute(eventType);
  const candidates = [...root.querySelectorAll(`[${attribute}]`)];
  if ("getAttribute" in root && typeof root.getAttribute === "function") {
    if (root.getAttribute(attribute) !== null) {
      candidates.unshift(root as Element);
    }
  }
  const matches = candidates.filter(
    (candidate) =>
      candidate.getAttribute(attribute) === targetKey &&
      componentBoundaryContains(boundary, candidate),
  );
  return matches.length === 1 ? matches[0] : undefined;
}

function isComponentActivationMount(
  value: unknown,
): value is ComponentActivationMount {
  return (
    typeof value === "object" &&
    value !== null &&
    "dispose" in value &&
    Effect.isEffect((value as { readonly dispose: unknown }).dispose)
  );
}

function isComponentActivationError(
  value: unknown,
): value is ComponentActivationError {
  if (typeof value !== "object" || value === null || !("_tag" in value)) {
    return false;
  }
  switch ((value as { readonly _tag: unknown })._tag) {
    case "ResumeComponentActivationNotFoundError":
    case "ResumeComponentNotAddressableError":
    case "ResumeComponentActivationDisposedError":
    case "ResumeComponentActivationResolutionError":
    case "ResumeComponentActivationExecutionError":
      return true;
    default:
      return false;
  }
}

function isPermanentPortableResolutionError(value: unknown): boolean {
  if (typeof value !== "object" || value === null || !("_tag" in value)) {
    return false;
  }
  switch ((value as { readonly _tag: unknown })._tag) {
    case "PortableCodeNotFoundError":
    case "PortableCodeIdentityMismatchError":
    case "PortableBuildMismatchError":
    case "PortableCaptureDecodeError":
      return true;
    default:
      return false;
  }
}

/**
 * Errors that make a boundary unresumable but leave it activatable: the
 * restored mount rolls back and one normal activation takes over.
 */
export type RestorationFallbackError =
  | StateBindingRestoreError
  | ResumeRestoredRenderError;

function isRestorationFallbackError(
  value: unknown,
): value is RestorationFallbackError {
  if (typeof value !== "object" || value === null || !("_tag" in value)) {
    return false;
  }
  switch ((value as { readonly _tag: unknown })._tag) {
    case "ResumeComponentPlanUnsupportedError":
    case "ResumeStateBindingMissingError":
    case "ResumeStateBindingUnexpectedError":
    case "ResumeStateSnapshotDecodeError":
    case "ResumePortableBehaviorAttachmentError":
    case "ResumeRestoredRenderError":
      return true;
    default:
      return false;
  }
}

/**
 * Snapshot the nodes a boundary region currently owns so a failed restored
 * render can be rolled back to the SSR content before activation retakes it.
 */
function captureBoundaryRegion(
  boundary: ComponentBoundary,
): ReadonlyArray<Node> {
  const captured: Node[] = [];
  let current = boundary.start.nextSibling;
  while (current !== null && current !== boundary.end) {
    captured.push(current);
    current = current.nextSibling;
  }
  return captured;
}

/**
 * Restore a boundary region to a previously captured node list. Returns a
 * failure reason when the DOM could not be rolled back, so the caller can
 * classify rather than throw.
 */
function restoreBoundaryRegion(
  boundary: ComponentBoundary,
  captured: ReadonlyArray<Node>,
): string | undefined {
  const current = captureBoundaryRegion(boundary);
  if (
    current.length === captured.length
    && current.every((node, index) => node === captured[index])
  ) {
    return undefined;
  }
  const parent = boundary.start.parentNode;
  if (parent === null || boundary.end.parentNode !== parent) {
    return `Component boundary "${boundary.componentId}" is no longer attached to one parent.`;
  }
  try {
    for (const node of current) parent.removeChild(node);
    for (const node of captured) parent.insertBefore(node, boundary.end);
    return undefined;
  } catch (error) {
    return `Component boundary "${boundary.componentId}" could not be rolled back: ${String(error)}`;
  }
}

/**
 * Mount a component from a committed binding snapshot. Setup is never run on
 * this path; the restored handles and render owner share one child Scope.
 */
function mountRestoredComponent<
  C extends Component.Component<any, any, any, any, any>,
>(
  componentId: ComponentId,
  boundary: ComponentBoundary,
  component: C,
  props: Component.PropsOf<C>,
  manifest: ValidatedManifest,
  runtime: ManagedRuntime.ManagedRuntime<any, any>,
  resolver: Portable.ResolverService,
  report: (diagnostic: ClientDiagnostic) => void,
): Effect.Effect<
  ComponentActivationMount,
  RestorationFallbackError | ResumeComponentActivationMountError,
  Component.Requirements<C>
> {
  return Effect.gen(function* () {
    const scope = yield* Scope.make();
    const allocate = Effect.gen(function* () {
      // Registered before restoration on purpose: Scope finalizers run LIFO,
      // so this must be the *last* finalizer to run. Otherwise refresh fibers
      // would be interrupted while restoration still reports "not disposed",
      // letting an interrupted refresh write into a disposing component.
      const refreshFibers = new Set<Fiber.Fiber<unknown, unknown>>();
      let stopRevalidation: (() => void) | undefined;
      yield* Scope.addFinalizer(
        scope,
        Effect.suspend(() => {
          stopRevalidation?.();
          stopRevalidation = undefined;
          const running = [...refreshFibers];
          refreshFibers.clear();
          return Effect.forEach(running, Fiber.interrupt, { discard: true });
        }),
      );
      const restored = yield* restoreStateBindingsInScope(
        component,
        manifest,
        componentId,
        props,
        scope,
      );
      // The render callback runs inside a reactive computation, which swallows
      // throws. Capture the first failure so a failed restored render becomes
      // a classified fallback instead of a boundary that claims readiness.
      let renderFailure: unknown;
      const capturedRegion = captureBoundaryRegion(boundary);
      const disposeRender = yield* Effect.try({
        try: () => {
          const target = componentBoundaryTarget(boundary);
          let initialized = false;
          let output: unknown;
          return mountWithManagedRuntime(
            () => {
              if (renderFailure !== undefined) return null;
              try {
                if (!initialized) {
                  initialized = true;
                  output = Component.renderWithBindings(
                    component,
                    props,
                    restored.bindings,
                  );
                }
                return typeof output === "function"
                  ? (output as () => unknown)()
                  : output;
              } catch (error) {
                renderFailure = error ?? new Error("Restored render failed.");
                return null;
              }
            },
            target,
            runtime,
            {
              scope,
              ownsScope: false,
            },
          );
        },
        catch: (error) =>
          new ResumeComponentActivationMountError({
            componentId,
            message: `Restored component boundary "${componentId}" could not mount: ${String(error)}`,
          }),
      });
      if (renderFailure !== undefined) {
        // Tear the partial restored mount down and roll the region back to the
        // SSR content so exactly one activation mount can claim it.
        yield* Effect.sync(disposeRender).pipe(Effect.ignore);
        const rollbackFailure = restoreBoundaryRegion(
          boundary,
          capturedRegion,
        );
        return yield* new ResumeRestoredRenderError({
          componentId,
          message: `Restored component boundary "${componentId}" failed to render: ${String(renderFailure)}${
            rollbackFailure === undefined ? "" : `; ${rollbackFailure}`
          }`,
        });
      }
      const queryEntries = Object.values(restored.queries).filter(
        (query) => query.reactivityKeys.length > 0,
      );
      stopRevalidation = onReactivityInvalidation((invalidated) => {
        const invalidatedSet = new Set(invalidated);
        for (const query of queryEntries) {
          if (
            !query.reactivityKeys.some((key) => invalidatedSet.has(key))
          ) {
            continue;
          }
          const refresh = query.refresh.pipe(
            Effect.provideService(Portable.Resolver, resolver),
          ) as Effect.Effect<void, RestoredQueryRefreshError, any>;
          let fiber: Fiber.Fiber<unknown, unknown>;
          try {
            fiber = runtime.runFork(refresh);
          } catch (error) {
            report({
              code: "component-query-refresh-failure",
              componentId,
              reason: `The managed runtime rejected restored query refresh for "${componentId}": ${String(error)}`,
            });
            continue;
          }
          // An invalidation racing teardown would otherwise add a fiber to the
          // already-cleared set and never be interrupted, leaking a fiber
          // handle. The refresh fails fast on the `disposed` check, but the
          // handle is still worth not stranding.
          if (disposed) {
            void Fiber.interrupt(fiber).pipe(Effect.runFork);
            continue;
          }
          refreshFibers.add(fiber);
          fiber.addObserver((exit) => {
            refreshFibers.delete(fiber);
            // Interruption is not a query failure: the scope finalizer
            // interrupts every in-flight refresh on ordinary dispose, so
            // reporting interrupted exits would emit a false
            // "refresh failed" diagnostic on normal teardown. This mirrors
            // the `expressionIsDormant` guard on the expression path.
            if (Exit.isFailure(exit) && !Cause.hasInterruptsOnly(exit.cause)) {
              report({
                code: "component-query-refresh-failure",
                componentId,
                reason: `A restored query refresh for "${componentId}" failed: ${Cause.pretty(exit.cause)}`,
              });
            }
          });
        }
      });
      let disposed = false;
      return {
        dispose: Effect.suspend(() => {
          if (disposed) return Effect.void;
          disposed = true;
          return Effect.sync(disposeRender).pipe(
            Effect.ensuring(Scope.close(scope, Exit.void)),
          );
        }),
      };
    }).pipe(
      Effect.onError((cause) => Scope.close(scope, Exit.failCause(cause))),
    );
    return yield* allocate;
  }).pipe(Effect.withSpan("Resume.mountRestoredComponent")) as Effect.Effect<
    ComponentActivationMount,
    RestorationFallbackError | ResumeComponentActivationMountError,
    Component.Requirements<C>
  >;
}

function mountActivatedComponent<
  C extends Component.Component<any, any, any, any, any>,
>(
  componentId: ComponentId,
  boundary: ComponentBoundary,
  component: C,
  props: Component.PropsOf<C>,
  runtime: ManagedRuntime.ManagedRuntime<any, any>,
): Effect.Effect<
  ComponentActivationMount,
  Component.Errors<C> | ResumeComponentActivationMountError,
  Component.Requirements<C>
> {
  return Effect.gen(function* () {
    const scope = yield* Scope.make();
    const allocate = Effect.gen(function* () {
      const bindings = yield* Component.setupEffect(component, props).pipe(
        Scope.provide(scope),
      );
      const disposeRender = yield* Effect.try({
        try: () => {
          const target = componentBoundaryTarget(boundary);
          let initialized = false;
          let output: unknown;
          return mountWithManagedRuntime(
            () => {
              if (!initialized) {
                output = Component.renderWithBindings(
                  component,
                  props,
                  bindings,
                );
                initialized = true;
              }
              return typeof output === "function"
                ? (output as () => unknown)()
                : output;
            },
            target,
            runtime,
            {
              scope,
              ownsScope: false,
            },
          );
        },
        catch: (error) =>
          new ResumeComponentActivationMountError({
            componentId,
            message: `Component boundary "${componentId}" could not mount: ${String(error)}`,
          }),
      });
      let disposed = false;
      return {
        dispose: Effect.suspend(() => {
          if (disposed) return Effect.void;
          disposed = true;
          return Effect.sync(disposeRender).pipe(
            Effect.ensuring(Scope.close(scope, Exit.void)),
          );
        }),
      };
    }).pipe(
      Effect.onError((cause) => Scope.close(scope, Exit.failCause(cause))),
    );
    return yield* allocate;
  }).pipe(Effect.withSpan("Resume.mountActivatedComponent"));
}

/**
 * Install the initial delegated client adapter for zero-argument portable
 * events. The caller owns the ManagedRuntime; disposing this installation only
 * removes its listeners, interrupts its fibers, and disposes activated
 * component regions.
 */
export function installClient<R, ER>(
  options: ClientInstallOptions<R, ER>,
): Effect.Effect<ClientInstallation, ClientInstallError> {
  return Effect.suspend(() => {
    // The root claim is made synchronously, in the same tick as the duplicate
    // check, so two concurrent installs on one root can never both pass the
    // guard. If installation subsequently fails or is interrupted, the claim
    // is released so the root does not become permanently unusable.
    const installationToken = Symbol();
    let claimed = false;
    const releaseClaim = () => {
      if (!claimed) return;
      claimed = false;
      if (activeClientInstallations.get(options.root) === installationToken) {
        activeClientInstallations.delete(options.root);
      }
    };
    return installClientClaimed(options, installationToken, () => {
      if (activeClientInstallations.has(options.root)) return false;
      activeClientInstallations.set(options.root, installationToken);
      claimed = true;
      return true;
    }).pipe(
      Effect.onExit((exit) =>
        Exit.isSuccess(exit) ? Effect.void : Effect.sync(releaseClaim)
      ),
      Effect.withSpan("Resume.installClient"),
    );
  });
}

function installClientClaimed<R, ER>(
  options: ClientInstallOptions<R, ER>,
  installationToken: symbol,
  claimRoot: () => boolean,
): Effect.Effect<ClientInstallation, ClientInstallError> {
  return Effect.gen(function* () {
    const expectedBuildId = yield* decodeBuildId(options.expectedBuildId);
    const manifest = yield* validateManifestValue(
      options.manifest,
      "client installation",
    );
    if (manifest.buildId !== expectedBuildId) {
      return yield* new ResumeClientBuildMismatchError({
        expected: expectedBuildId,
        actual: manifest.buildId,
        message: "The resume manifest belongs to a different client build.",
      });
    }
    if (!claimRoot()) {
      return yield* new ResumeDuplicateClientInstallationError({
        message:
          "This DOM root already has an active resumability installation. Dispose it before installing another.",
      });
    }

    const expressionEntries = expressionEntriesOf(manifest);
    const boundaries = yield* scanComponentBoundaries(options.root, manifest);
    const events = manifest.events as Readonly<
      Record<string, typeof EventEntrySchema.Type>
    >;
    for (const [rawEventId, entry] of Object.entries(events)) {
      if (
        entry.invocation === ActivationProjection
        && !MouseEventProjection.supportsEventType(entry.type)
      ) {
        return yield* new ResumeUnsupportedActivationEventTypeError({
          eventId: eventIdFromValidatedString(rawEventId),
          eventType: entry.type,
          projection: entry.projection,
          message:
            `Activation event "${rawEventId}" uses ${entry.projection} with unsupported event type "${entry.type}".`,
        });
      }
    }
    const componentSnapshots =
      manifest.version === 1 ? {} : manifest.components;
    yield* validateExpressionDependencyMetadata(expressionEntries);
    const eventTypes = new Set<EventType>(
      Object.values(events).map((entry) => entry.type),
    );
    yield* validateMarkers(options.root, events, eventTypes, manifest.installationId);
    yield* validateActivationEventOwnership(
      options.root,
      events,
      boundaries,
      componentSnapshots,
    );
    // One traversal discovers text regions *and* element markers, so a manifest
    // whose declared kind contradicts the DOM (a text entry whose instance also
    // carries an element marker, or the reverse) is a typed kind-mismatch
    // failure rather than a silently accepted install. Ownership validation and
    // installation-marker cleanup are part of the same scan.
    const expressionTargets =
      yield* scanExpressionTargetsWithComponentBoundaries(
        options.root,
        manifest,
        boundaries,
      );
    const resolver = yield* Portable.makeResolver(options.resolverEntries);

    return yield* Effect.try({
      try: () => {
        let disposed = false;
        const fibers = new Set<Fiber.Fiber<unknown, unknown>>();
        const processed = new WeakMap<Event, Set<string>>();
        const claimedInteractions = new WeakSet<Event>();
        const listeners = new Map<string, EventListener>();
        // M11b fragment scopes: events of mounted fragments, keyed by the
        // client-assigned scope id their rewritten DOM markers carry
        // (`DQ-015`). They dispatch through THIS installation's listeners —
        // a mount never adds root listeners of its own.
        const fragmentScopes = new Map<
          string,
          {
            readonly events: Readonly<
              Record<string, typeof EventEntrySchema.Type>
            >;
            disposed: boolean;
          }
        >();
        const regionFragments = new Map<string, { dispose: () => void }>();
        let fragmentScopeCounter = 0;
        const bindingValues = new Map<string, unknown>();
        const bindingOverrides = new Map<
          ComponentId,
          Map<BindingName, unknown>
        >();
        for (
          const [componentId, component] of Object.entries(
            componentSnapshots,
          ) as Array<[ComponentId, ComponentSnapshot]>
        ) {
          for (
            const [bindingName, binding] of Object.entries(
              component.bindings,
            )
          ) {
            bindingValues.set(
              bindingReactivityKey(componentId, bindingName),
              binding.value,
            );
          }
        }
        type ActivationResume = (
          effect: Effect.Effect<void, ComponentActivationError>,
        ) => void;
        interface RestoredExpressionController {
          readonly expressionId: ExpressionId;
          readonly target: ScannedExpressionTarget;
          readonly entry: ExpressionEntry;
          disposed: boolean;
          dirty: boolean;
          queued: boolean;
          running?: Fiber.Fiber<unknown, unknown>;
          /** Present only after a structural region's first patch. */
          structural?: StructuralRegionState;
        }
        interface BoundaryController {
          readonly boundary: ComponentBoundary;
          readonly snapshot: ComponentSnapshot;
          state: ComponentBoundaryState;
          /**
           * A dormant descendant remains rollback-capable while an ancestor
           * stages activation, but must not accept writes or dispatch work
           * into DOM that the ancestor may replace.
           */
          quiescedBy?: ComponentId;
          /**
           * The mode that claimed this boundary's in-flight transition.
           * First-wins: a later caller with a conflicting mode joins the
           * transition, and the discarded mode is reported as a diagnostic
           * rather than silently coalesced.
           */
          transitionMode?: "resume" | "activate";
          fiber?: Fiber.Fiber<ComponentActivationMount, unknown>;
          mount?: ComponentActivationMount;
          failure?: ComponentActivationError;
          readonly subscribers: Set<ActivationResume>;
          readonly expressions: Set<RestoredExpressionController>;
        }
        const controllers = new Map<ComponentId, BoundaryController>();
        for (const [componentId, boundary] of boundaries) {
          const snapshot = componentSnapshots[componentId];
          if (snapshot !== undefined) {
            controllers.set(componentId, {
              boundary,
              snapshot,
              state: { status: "dormant" },
              subscribers: new Set(),
              expressions: new Set(),
            });
          }
        }
        const expressionControllers = new Map<
          ExpressionId,
          RestoredExpressionController
        >();
        const expressionSubscribers = new Map<
          string,
          Set<RestoredExpressionController>
        >();
        for (const [expressionId, target] of expressionTargets) {
          const entry = expressionEntries[expressionId];
          if (entry === undefined) continue;
          const expressionController: RestoredExpressionController = {
            expressionId,
            target,
            entry,
            disposed: false,
            dirty: false,
            queued: false,
          };
          expressionControllers.set(expressionId, expressionController);
          for (const key of entry.deps) {
            let subscribers = expressionSubscribers.get(key);
            if (subscribers === undefined) {
              subscribers = new Set();
              expressionSubscribers.set(key, subscribers);
            }
            subscribers.add(expressionController);
          }
          if (entry.component !== undefined) {
            controllers.get(entry.component)?.expressions.add(
              expressionController,
            );
          }
        }

        const report = (diagnostic: ClientDiagnostic): void => {
          try {
            options.onDiagnostic?.(diagnostic);
          } catch {
            // Observability callbacks must never compromise dispatch or cleanup.
          }
        };
        /**
         * Close the Scopes of rows the reconciler just dropped. `runFork`
         * begins execution synchronously, so synchronous finalizers run before
         * this returns — disposal is observable at the moment of removal, not
         * at unmount.
         */
        const closeStructuralRowScopes = (
          scopes: ReadonlyArray<ReturnType<typeof Scope.makeUnsafe>>,
        ): void => {
          if (scopes.length === 0) return;
          let fiber: Fiber.Fiber<unknown, unknown>;
          try {
            fiber = options.runtime.runFork(
              Effect.forEach(
                scopes,
                (scope) => Scope.close(scope, Exit.void),
                { discard: true },
              ),
            );
          } catch {
            return;
          }
          fibers.add(fiber);
          fiber.addObserver(() => {
            fibers.delete(fiber);
          });
        };
        const notifyActivation = (
          controller: BoundaryController,
          effect: Effect.Effect<void, ComponentActivationError>,
        ): void => {
          const subscribers = [...controller.subscribers];
          controller.subscribers.clear();
          for (const resume of subscribers) resume(effect);
        };
        const disposedActivationError = (
          componentId: ComponentId,
        ): ResumeComponentActivationDisposedError =>
          new ResumeComponentActivationDisposedError({
            componentId,
            message: `Component boundary "${componentId}" has been disposed.`,
          });
        const expressionIsDormant = (
          controller: RestoredExpressionController,
        ): boolean => {
          if (disposed || controller.disposed) return false;
          const componentId = controller.entry.component;
          if (componentId === undefined) return true;
          const boundary = controllers.get(componentId);
          return boundary?.state.status === "dormant"
            && boundary.quiescedBy === undefined;
        };
        const quiesceExpression = (
          controller: RestoredExpressionController,
        ): Effect.Effect<void> =>
          Effect.suspend(() => {
            if (controller.disposed) return Effect.void;
            if (
              controller.dirty
              || controller.queued
              || controller.running !== undefined
            ) {
              // Preserve the need to recompute if staging rolls back.
              controller.dirty = true;
            }
            controller.queued = false;
            const running = controller.running;
            controller.running = undefined;
            if (running === undefined) return Effect.void;
            fibers.delete(running);
            return Fiber.interrupt(running);
          });
        const quiesceBoundaryExpressions = (
          controller: BoundaryController,
        ): Effect.Effect<void> =>
          Effect.forEach(
            controller.expressions,
            quiesceExpression,
            { discard: true },
          );
        const rearmBoundaryExpressions = (
          controller: BoundaryController,
        ): void => {
          if (
            controller.state.status !== "dormant"
            || controller.quiescedBy !== undefined
          ) {
            return;
          }
          for (const expression of controller.expressions) {
            if (expression.dirty) scheduleExpression(expression);
          }
        };
        const disposeExpression = (
          controller: RestoredExpressionController,
        ): Effect.Effect<void> =>
          Effect.suspend(() => {
            if (controller.disposed) return Effect.void;
            controller.disposed = true;
            controller.dirty = false;
            controller.queued = false;
            expressionControllers.delete(controller.expressionId);
            for (const key of controller.entry.deps) {
              const subscribers = expressionSubscribers.get(key);
              subscribers?.delete(controller);
              if (subscribers?.size === 0) {
                expressionSubscribers.delete(key);
              }
            }
            // A structural region's surviving row Scopes close with the
            // installation; rows removed earlier already closed theirs at the
            // moment of removal.
            const rowScopes = controller.structural === undefined
              ? []
              : [...controller.structural.rows.values()].map(
                  (row) => row.scope,
                );
            controller.structural = undefined;
            const closeRows = rowScopes.length === 0
              ? Effect.void
              : Effect.forEach(
                  rowScopes,
                  (scope) => Scope.close(scope, Exit.void),
                  { discard: true },
                );
            const running = controller.running;
            controller.running = undefined;
            if (running === undefined) return closeRows;
            fibers.delete(running);
            return Effect.andThen(Fiber.interrupt(running), closeRows);
          });
        const disposeBoundaryExpressions = (
          controller: BoundaryController,
        ): Effect.Effect<void> =>
          Effect.forEach(
            [...controller.expressions],
            disposeExpression,
            { discard: true },
          ).pipe(
            Effect.andThen(
              Effect.sync(() => {
                controller.expressions.clear();
              }),
            ),
          );
        const launchExpression = (
          controller: RestoredExpressionController,
        ): void => {
          if (
            !expressionIsDormant(controller)
            || controller.running !== undefined
          ) {
            return;
          }
          controller.dirty = false;
          let phase: "resolution" | "execution" = "resolution";
          const values = (
            controller.entry.inputs ?? controller.entry.deps
          ).map((key) =>
            bindingValues.get(key)
          );
          const evaluate = Effect.gen(function* () {
            const resolved = yield* Portable.resolve<
              readonly [context: ExpressionContext],
              unknown,
              unknown,
              never
            >(controller.entry.code);
            phase = "execution";
            return yield* Effect.scoped(
              resolved.run({ values }),
            );
          }).pipe(
            Effect.provideService(Portable.Resolver, resolver),
          ) as Effect.Effect<unknown, unknown, R>;

          let fiber: Fiber.Fiber<unknown, unknown>;
          try {
            fiber = options.runtime.runFork(evaluate);
          } catch (error) {
            report({
              code: "client-runtime-failure",
              expressionId: controller.expressionId,
              ...(controller.entry.component === undefined
                ? {}
                : { componentId: controller.entry.component }),
              reason: `The managed runtime rejected expression "${controller.expressionId}": ${String(error)}`,
            });
            return;
          }
          controller.running = fiber;
          fibers.add(fiber);
          fiber.addObserver((exit) => {
            fibers.delete(fiber);
            if (controller.running === fiber) {
              controller.running = undefined;
            }
            if (!expressionIsDormant(controller)) return;
            if (Exit.isFailure(exit)) {
              report({
                code: phase === "resolution"
                  ? "expression-resolution-failure"
                  : "expression-execution-failure",
                expressionId: controller.expressionId,
                ...(controller.entry.component === undefined
                  ? {}
                  : { componentId: controller.entry.component }),
                reason: Cause.pretty(exit.cause),
              });
            } else if (!controller.dirty) {
              const value = exit.value;
              const target = controller.target;
              const ownerBoundary = controller.entry.component === undefined
                ? undefined
                : controllers.get(controller.entry.component)?.boundary;
              if (target.kind === "structural") {
                const validated = validateStructuralOutput(
                  target.mode,
                  value,
                );
                if (!validated.ok) {
                  report({
                    code: "expression-execution-failure",
                    expressionId: controller.expressionId,
                    ...(controller.entry.component === undefined
                      ? {}
                      : { componentId: controller.entry.component }),
                    reason: `Expression "${controller.expressionId}" returned invalid structural output: ${validated.reason}.`,
                  });
                } else {
                  try {
                    const patched = patchStructuralExpressionTarget(
                      target,
                      controller.structural,
                      validated.rows,
                      ownerBoundary,
                    );
                    controller.structural = patched.state;
                    closeStructuralRowScopes(patched.removedScopes);
                  } catch (error) {
                    report({
                      code: "expression-patch-failure",
                      expressionId: controller.expressionId,
                      ...(controller.entry.component === undefined
                        ? {}
                        : { componentId: controller.entry.component }),
                      reason: `Expression "${controller.expressionId}" could not patch its SSR region: ${String(error)}`,
                    });
                  }
                }
              } else if (!isSupportedExpressionOutput(target, value)) {
                report({
                  code: "expression-execution-failure",
                  expressionId: controller.expressionId,
                  ...(controller.entry.component === undefined
                    ? {}
                    : { componentId: controller.entry.component }),
                  reason: `Expression "${controller.expressionId}" returned unsupported ${
                    value === null ? "null" : typeof value
                  } output.`,
                });
              } else {
                try {
                  patchExpressionTarget(
                    target,
                    value as ExpressionOutput,
                    ownerBoundary,
                  );
                } catch (error) {
                  report({
                    code: "expression-patch-failure",
                    expressionId: controller.expressionId,
                    ...(controller.entry.component === undefined
                      ? {}
                      : { componentId: controller.entry.component }),
                    reason: `Expression "${controller.expressionId}" could not patch its SSR region: ${String(error)}`,
                  });
                }
              }
            }
            if (controller.dirty) {
              scheduleExpression(controller);
            }
          });
        };
        const scheduleExpression = (
          controller: RestoredExpressionController,
        ): void => {
          if (!expressionIsDormant(controller)) return;
          controller.dirty = true;
          if (controller.queued || controller.running !== undefined) return;
          controller.queued = true;
          queueMicrotask(() => {
            controller.queued = false;
            launchExpression(controller);
          });
        };
        const notifyExpressions = (
          invalidated: ReadonlyArray<string>,
          includeBindingKeys = false,
        ): void => {
          const scheduled = new Set<RestoredExpressionController>();
          for (const key of invalidated) {
            if (!includeBindingKeys && isBindingReactivityKey(key)) {
              continue;
            }
            for (const controller of expressionSubscribers.get(key) ?? []) {
              if (!scheduled.has(controller)) {
                scheduled.add(controller);
                scheduleExpression(controller);
              }
            }
          }
        };
        const stopExpressionInvalidation = onReactivityInvalidation(
          notifyExpressions,
        );
        const disposeBoundary = (
          controller: BoundaryController,
        ): Effect.Effect<void> =>
          Effect.suspend(() => {
            if (controller.state.status === "disposed") return Effect.void;
            controller.state = { status: "disposed" };
            notifyActivation(
              controller,
              Effect.fail(
                disposedActivationError(controller.boundary.componentId),
              ),
            );
            const fiber = controller.fiber;
            controller.fiber = undefined;
            if (fiber !== undefined) fibers.delete(fiber);
            const mount = controller.mount;
            controller.mount = undefined;
            const interruptActivation =
              fiber === undefined
                ? Effect.void
                : Fiber.interrupt(fiber).pipe(
                    Effect.andThen(Fiber.await(fiber)),
                    Effect.flatMap((exit) =>
                      Exit.isSuccess(exit) ? exit.value.dispose : Effect.void,
                    ),
                  );
            return Effect.all(
              [
                disposeBoundaryExpressions(controller),
                interruptActivation,
                mount === undefined ? Effect.void : mount.dispose,
              ],
              { discard: true },
            );
          });
        const isDescendantOf = (
          candidate: BoundaryController,
          ancestorId: ComponentId,
        ): boolean => {
          let parentId = candidate.boundary.parentComponentId;
          while (parentId !== undefined) {
            if (parentId === ancestorId) return true;
            parentId = boundaries.get(parentId)?.parentComponentId;
          }
          return false;
        };
        const boundaryDepth = (controller: BoundaryController): number => {
          let depth = 0;
          let parentId = controller.boundary.parentComponentId;
          while (parentId !== undefined) {
            depth += 1;
            parentId = boundaries.get(parentId)?.parentComponentId;
          }
          return depth;
        };
        const closestBoundary = (
          path: ReadonlyArray<EventTarget>,
        ): BoundaryController | undefined =>
          [...controllers.values()]
            .filter(
              (controller) =>
                path.some((target) =>
                  componentBoundaryContains(controller.boundary, target)
                ),
            )
            .sort((left, right) =>
              boundaryDepth(right) - boundaryDepth(left)
            )[0];
        const isTransitionable = (
          controller: BoundaryController,
        ): boolean =>
          controller.state.status === "dormant"
          || controller.state.status === "resuming"
          || controller.state.status === "activating";
        /**
         * Resolve the single boundary allowed to claim an interaction.
         *
         * Only the innermost boundary containing the target may own the event.
         * When that boundary has been quiesced by an ancestor staging its own
         * activation, the quiescing ancestor is the legitimate owner. Any other
         * ineligible state (failed/disposed) yields no owner — the walk must
         * never silently promote an unrelated ancestor.
         */
        const claimingBoundary = (
          target: EventTarget,
        ): BoundaryController | undefined => {
          const innermost = closestBoundary([target]);
          if (innermost === undefined) return undefined;
          if (innermost.quiescedBy !== undefined) {
            const owner = controllers.get(innermost.quiescedBy);
            return owner !== undefined && isTransitionable(owner)
              ? owner
              : undefined;
          }
          return isTransitionable(innermost) ? innermost : undefined;
        };
        const descendantsOf = (
          componentId: ComponentId,
        ): ReadonlyArray<BoundaryController> =>
          [...controllers.values()].filter((candidate) =>
            isDescendantOf(candidate, componentId)
          );
        const disposeDescendants = (
          componentId: ComponentId,
        ): Effect.Effect<void> =>
          Effect.forEach(
            descendantsOf(componentId),
            disposeBoundary,
            { discard: true },
          );
        const startTransition = (
          controller: BoundaryController,
          mode: "resume" | "activate",
        ): void => {
          const componentId = controller.boundary.componentId;
          const descriptor = controller.snapshot.activation;
          if (descriptor === undefined) {
            const failure = new ResumeComponentNotAddressableError({
              componentId,
              message: `Component boundary "${componentId}" has no portable activation entry.`,
            });
            controller.failure = failure;
            controller.state = {
              status: "failed",
              reason: failure.message,
            };
            notifyActivation(controller, Effect.fail(failure));
            return;
          }

          controller.transitionMode = mode;
          controller.state = {
            status: mode === "resume" ? "resuming" : "activating",
          };
          const stagedDescendants = descendantsOf(componentId).filter(
            (descendant) =>
              descendant.state.status === "dormant"
              && descendant.quiescedBy === undefined,
          );
          for (const descendant of stagedDescendants) {
            descendant.quiescedBy = componentId;
          }
          const releaseStagedDescendants = (): void => {
            for (const descendant of stagedDescendants) {
              if (descendant.quiescedBy !== componentId) continue;
              descendant.quiescedBy = undefined;
              rearmBoundaryExpressions(descendant);
            }
          };
          let phase: "resolution" | "execution" = "resolution";
          let terminalFailure = false;
          let stagedMount: ComponentActivationMount | undefined;
          const activationBody = Effect.gen(function* () {
            yield* quiesceBoundaryExpressions(controller);
            yield* Effect.forEach(
              stagedDescendants,
              quiesceBoundaryExpressions,
              { discard: true },
            );
            const resolved = yield* Portable.resolve<
              readonly [ComponentActivationContext],
              ComponentActivationMount,
              unknown,
              unknown
            >(descriptor);
            phase = "execution";
            const mount = yield* resolved.run({
              componentId,
              mount: (component, props) => {
                if (mode === "activate") {
                  return mountActivatedComponent(
                    componentId,
                    controller.boundary,
                    component,
                    props,
                    options.runtime,
                  );
                }
                return Effect.gen(function* () {
                  const restored = yield* Effect.exit(
                    mountRestoredComponent(
                      componentId,
                      controller.boundary,
                      component,
                      props,
                      manifestWithBindingOverrides(
                        manifest,
                        componentId,
                        bindingOverrides,
                      ),
                      options.runtime,
                      resolver,
                      report,
                    ),
                  );
                  if (Exit.isSuccess(restored)) {
                    return restored.value;
                  }
                  if (controller.state.status === "disposed") {
                    return yield* Effect.interrupt;
                  }
                  const restorationError = Cause.findErrorOption(
                    restored.cause,
                  );
                  if (
                    restorationError._tag === "None" ||
                    !isRestorationFallbackError(restorationError.value)
                  ) {
                    return yield* (
                      Effect.failCause(restored.cause) as Effect.Effect<
                        never,
                        ResumeComponentActivationMountError
                      >
                    );
                  }
                  controller.state = { status: "activating" };
                  controller.transitionMode = "activate";
                  report({
                    code: "component-resumption-fallback",
                    componentId,
                    reason: `Component boundary "${componentId}" could not resume and is falling back to activation after ${restorationError.value._tag}: ${restorationError.value.message}`,
                  });
                  return yield* mountActivatedComponent(
                    componentId,
                    controller.boundary,
                    component,
                    props,
                    options.runtime,
                  );
                });
              },
            });
            if (!isComponentActivationMount(mount)) {
              return yield* new ResumeComponentActivationExecutionError({
                componentId,
                message: `Component activation "${descriptor.id}" returned an invalid mount handle.`,
              });
            }
            stagedMount = mount;
            // Commit is uninterruptible: after the active DOM/listeners exist,
            // dormant writers and descendant owners must be surrendered as
            // one ownership transition. The staged mount is disposed by the
            // outer finalizer if anything fails before this point completes.
            yield* Effect.uninterruptible(
              disposeBoundaryExpressions(controller).pipe(
                Effect.andThen(disposeDescendants(componentId)),
              ),
            );
            return mount;
          });
          const activation = activationBody.pipe(
            Effect.provideService(Portable.Resolver, resolver),
            Effect.onError(() =>
              stagedMount === undefined ? Effect.void : stagedMount.dispose
            ),
            Effect.catchCause((cause) => {
              const typed = Cause.findErrorOption(cause);
              terminalFailure =
                Cause.hasDies(cause)
                || Cause.hasInterrupts(cause)
                || (
                  phase === "resolution"
                  && typed._tag === "Some"
                  && isPermanentPortableResolutionError(typed.value)
                );
              if (
                typed._tag === "Some" &&
                isComponentActivationError(typed.value)
              ) {
                return Effect.fail(typed.value);
              }
              return Effect.fail(
                phase === "resolution"
                  ? new ResumeComponentActivationResolutionError({
                      componentId,
                      message: `Component activation "${descriptor.id}" could not be resolved: ${Cause.pretty(cause)}`,
                    })
                  : new ResumeComponentActivationExecutionError({
                      componentId,
                      message: `Component activation "${descriptor.id}" failed: ${Cause.pretty(cause)}`,
                    }),
              );
            }),
            Effect.tapError(() =>
              terminalFailure
                ? disposeBoundaryExpressions(controller)
                : Effect.void
            ),
          ) as Effect.Effect<
            ComponentActivationMount,
            ComponentActivationError,
            R
          >;

          let fiber: Fiber.Fiber<ComponentActivationMount, unknown>;
          try {
            fiber = options.runtime.runFork(activation);
          } catch (error) {
            const failure = new ResumeComponentActivationExecutionError({
              componentId,
              message: `The managed runtime rejected component activation "${descriptor.id}": ${String(error)}`,
            });
            controller.failure = failure;
            controller.state = {
              status: "failed",
              reason: failure.message,
            };
            releaseStagedDescendants();
            notifyActivation(controller, Effect.fail(failure));
            return;
          }
          controller.fiber = fiber;
          fibers.add(fiber);
          fiber.addObserver((exit) => {
            fibers.delete(fiber);
            if (controller.fiber === fiber) controller.fiber = undefined;
            controller.transitionMode = undefined;
            if (controller.state.status === "disposed") return;
            if (Exit.isSuccess(exit)) {
              controller.mount = exit.value;
              controller.state = { status: "active" };
              notifyActivation(controller, Effect.void);
              return;
            }
            const typed = Cause.findErrorOption(exit.cause);
            const error =
              typed._tag === "Some" && isComponentActivationError(typed.value)
                ? typed.value
                : new ResumeComponentActivationExecutionError({
                    componentId,
                  message: `Component activation "${descriptor.id}" failed: ${Cause.pretty(exit.cause)}`,
                  });
            controller.failure = error;
            if (terminalFailure) {
              controller.state = {
                status: "failed",
                reason: error.message,
              };
            } else {
              controller.state = { status: "dormant" };
              controller.failure = undefined;
            }
            releaseStagedDescendants();
            rearmBoundaryExpressions(controller);
            notifyActivation(controller, Effect.fail(error));
          });
        };
        const transition = (
          rawComponentId: string,
          mode: "resume" | "activate",
        ): Effect.Effect<void, ComponentActivationError> =>
          Effect.callback((resume) => {
            const controller = controllers.get(rawComponentId as ComponentId);
            if (controller === undefined) {
              resume(
                Effect.fail(
                  new ResumeComponentActivationNotFoundError({
                    componentId: rawComponentId,
                    message: `No component boundary exists for "${rawComponentId}".`,
                  }),
                ),
              );
              return;
            }
            switch (controller.state.status) {
              case "active":
                resume(Effect.void);
                return;
              case "disposed":
                resume(
                  Effect.fail(
                    disposedActivationError(controller.boundary.componentId),
                  ),
                );
                return;
              case "failed":
                resume(
                  Effect.fail(
                    controller.failure ??
                      new ResumeComponentActivationExecutionError({
                        componentId: controller.boundary.componentId,
                        message: controller.state.reason,
                      }),
                  ),
                );
                return;
              case "dormant":
                controller.subscribers.add(resume);
                startTransition(controller, mode);
                break;
              case "resuming":
              case "activating": {
                // First-wins: the in-flight transition keeps its mode. The
                // joining caller's conflicting mode is discarded, which must
                // be observable instead of silent.
                const inFlight = controller.transitionMode
                  ?? (controller.state.status === "resuming"
                    ? "resume"
                    : "activate");
                if (inFlight !== mode) {
                  report({
                    code: "component-transition-mode-conflict",
                    componentId: controller.boundary.componentId,
                    reason: `Component boundary "${controller.boundary.componentId}" is already transitioning in "${inFlight}" mode; the requested "${mode}" mode was discarded and this request joined the in-flight transition.`,
                  });
                }
                controller.subscribers.add(resume);
                break;
              }
            }
            return Effect.sync(() => {
              controller.subscribers.delete(resume);
            });
          });
        const activate = (
          rawComponentId: string,
        ): Effect.Effect<void, ComponentActivationError> =>
          transition(rawComponentId, "activate");
        const resumeBoundary = (
          rawComponentId: string,
        ): Effect.Effect<void, ComponentActivationError> =>
          transition(rawComponentId, "resume");
        const removeListener = (
          eventType: string,
          listener: EventListener,
        ): void => {
          try {
            options.root.removeEventListener(eventType, listener, true);
          } catch (error) {
            report({
              code: "client-runtime-failure",
              eventType,
              reason: `Resume event listener removal failed: ${String(error)}`,
            });
          }
        };

        const launch = (
          eventType: EventType,
          eventId: string,
          entry: typeof PortableEventEntrySchema.Type,
        ): void => {
          let phase: "resolution" | "execution" = "resolution";
          const dispatch = Effect.gen(function* () {
            const resolved = yield* Portable.resolve<
              readonly [],
              unknown,
              unknown,
              unknown
            >(entry.code);
            phase = "execution";
            return yield* Effect.scoped(resolved.run());
          }).pipe(
            Effect.provideService(Portable.Resolver, resolver),
            Effect.exit,
            Effect.tap((exit) =>
              Exit.isFailure(exit) && !disposed
                ? Effect.sync(() =>
                    report({
                      code:
                        phase === "resolution"
                          ? "dispatch-resolution-failure"
                          : "dispatch-execution-failure",
                      eventType,
                      eventId,
                      reason: Cause.pretty(exit.cause),
                    }),
                  )
                : Effect.void,
            ),
          ) as Effect.Effect<Exit.Exit<unknown, unknown>, never, R>;

          let fiber: Fiber.Fiber<unknown, unknown>;
          try {
            fiber = options.runtime.runFork(dispatch) as Fiber.Fiber<
              unknown,
              unknown
            >;
          } catch (error) {
            report({
              code: "client-runtime-failure",
              eventType,
              eventId,
              reason: `The managed runtime rejected the dispatch: ${String(error)}`,
            });
            return;
          }
          fibers.add(fiber);
          fiber.addObserver((exit) => {
            fibers.delete(fiber);
            if (Exit.isFailure(exit) && !disposed) {
              report({
                code: "client-runtime-failure",
                eventType,
                eventId,
                reason: Cause.pretty(exit.cause),
              });
            }
          });
        };

        const launchActivationHandoff = (
          eventType: EventType,
          eventId: string,
          entry: typeof ActivationEventEntrySchema.Type,
          controller: BoundaryController,
          projection: ActivationProjectionValue,
        ): void => {
          const componentId = controller.boundary.componentId;
          const handoff = Effect.gen(function* () {
            yield* resumeBoundary(componentId);
            if (
              disposed ||
              controller.state.status === "disposed"
            ) {
              return;
            }
            const target = findBoundaryReplayTarget(
              options.root,
              controller.boundary,
              eventType,
              entry.targetKey,
            );
            if (target === undefined) {
              return yield* new ResumeEventHandoffError({
                componentId,
                eventId: eventIdFromValidatedString(eventId),
                eventType,
                message: `Activation committed without exactly one "${entry.targetKey}" replay target.`,
              });
            }
            if (
              !replayActivationEvent(
                target,
                eventType,
                entry.targetKey,
                projection,
              )
            ) {
              return yield* new ResumeEventHandoffError({
                componentId,
                eventId: eventIdFromValidatedString(eventId),
                eventType,
                message: `Activation committed without a replayable "${entry.targetKey}" listener.`,
              });
            }
          }).pipe(
            Effect.exit,
            Effect.tap((exit) =>
              Exit.isFailure(exit) && !disposed
                ? Effect.sync(() =>
                    report({
                      code: "event-handoff-failure",
                      eventType,
                      eventId,
                      componentId,
                      reason: Cause.pretty(exit.cause),
                    }),
                  )
                : Effect.void,
            ),
          ) as Effect.Effect<unknown, never, R>;

          let fiber: Fiber.Fiber<unknown, unknown>;
          try {
            fiber = options.runtime.runFork(handoff);
          } catch (error) {
            report({
              code: "client-runtime-failure",
              eventType,
              eventId,
              componentId,
              reason: `The managed runtime rejected event handoff: ${String(error)}`,
            });
            return;
          }
          fibers.add(fiber);
          fiber.addObserver(() => {
            fibers.delete(fiber);
          });
        };

        // Extracted so a fragment mount (`DQ-014`/M11b) can install a root
        // listener for an event type the page itself never used.
        const installListener = (eventType: EventType): void => {
          if (listeners.has(eventType)) return;
          const listener: EventListener = (event) => {
            if (disposed) return;
            const path = eventPathWithinRoot(event, options.root);
            for (const target of path) {
              const marker = readMarker(target, eventType);
              if (marker === null) continue;
              // DQ-009: a marker scoped to another installation is not ours to
              // dispatch — a nested fragment's events must never resolve
              // against the page's table, or vice versa.
              const scopedEventId = unscopeEventMarker(marker, manifest.installationId);
              if (scopedEventId === undefined) {
                // M11b: a foreign-scoped marker may belong to a mounted
                // fragment. Its events resolve against that fragment's own
                // table — never the page's — through this same listener.
                const separator = marker.indexOf(":");
                if (separator <= 0) continue;
                const fragment = fragmentScopes.get(marker.slice(0, separator));
                if (fragment === undefined || fragment.disposed) continue;
                const fragmentEntry =
                  fragment.events[marker.slice(separator + 1)];
                if (
                  fragmentEntry === undefined
                  || fragmentEntry.type !== eventType
                  || fragmentEntry.invocation === ActivationProjection
                ) {
                  continue;
                }
                if (claimedInteractions.has(event)) return;
                let fragmentEventIds = processed.get(event);
                if (fragmentEventIds === undefined) {
                  fragmentEventIds = new Set();
                  processed.set(event, fragmentEventIds);
                }
                if (fragmentEventIds.has(marker)) continue;
                fragmentEventIds.add(marker);
                claimedInteractions.add(event);
                launch(eventType, marker, fragmentEntry);
                return;
              }
              const entry = events[scopedEventId];
              if (entry === undefined) {
                report({
                  code: "unknown-event-marker",
                  eventType,
                  eventId: marker,
                  reason: `No resume manifest entry exists for event marker "${marker}".`,
                });
                continue;
              }
              if (entry.type !== eventType) {
                report({
                  code: "event-type-mismatch",
                  eventType,
                  eventId: marker,
                  reason: `Event marker "${marker}" belongs to "${entry.type}", not "${eventType}".`,
                });
                continue;
              }
              // Single documented claim policy: the closest marker on the
              // event path (portable OR activation) consumes the interaction
              // and stops further markers from firing a second owner, exactly
              // as a real DOM handler calling stopPropagation would. Once any
              // marker has claimed this event, no later marker acts.
              if (claimedInteractions.has(event)) return;

              if (
                closestBoundary([target])?.state.status === "active"
              ) {
                continue;
              }

              if (entry.invocation === ActivationProjection) {
                const controller = claimingBoundary(target);
                if (controller === undefined) {
                  const owner = closestBoundary([target]);
                  if (owner !== undefined) {
                    report({
                      code: "event-handoff-failure",
                      eventType,
                      eventId: marker,
                      componentId: owner.boundary.componentId,
                      reason: `Component boundary "${owner.boundary.componentId}" owns this activation event but is "${owner.state.status}"; the interaction was not handed to an ancestor.`,
                    });
                  }
                  continue;
                }
                let projection: ActivationProjectionValue;
                try {
                  projection = MouseEventProjection.capture(event);
                } catch (error) {
                  report({
                    code: "event-handoff-failure",
                    eventType,
                    eventId: marker,
                    componentId: controller.boundary.componentId,
                    reason: `The native event could not be projected synchronously: ${String(error)}`,
                  });
                  return;
                }
                claimedInteractions.add(event);
                if (typeof event.preventDefault === "function") {
                  event.preventDefault();
                }
                if (typeof event.stopImmediatePropagation === "function") {
                  event.stopImmediatePropagation();
                } else if (typeof event.stopPropagation === "function") {
                  event.stopPropagation();
                }
                launchActivationHandoff(
                  eventType,
                  marker,
                  entry,
                  controller,
                  projection,
                );
                return;
              }

              let eventIds = processed.get(event);
              if (eventIds === undefined) {
                eventIds = new Set();
                processed.set(event, eventIds);
              }
              if (eventIds.has(marker)) continue;
              eventIds.add(marker);
              // Portable markers claim symmetrically with activation markers:
              // the closest one consumes the interaction and stops the walk so
              // no ancestor marker of the same type fires a second owner.
              claimedInteractions.add(event);
              launch(eventType, marker, entry);
              return;
            }
          };
          try {
            options.root.addEventListener(eventType, listener, true);
            listeners.set(eventType, listener);
          } catch (error) {
            stopExpressionInvalidation();
            for (const controller of expressionControllers.values()) {
              controller.disposed = true;
              controller.dirty = false;
              controller.queued = false;
            }
            for (const [installedType, installedListener] of listeners) {
              removeListener(installedType, installedListener);
            }
            listeners.clear();
            throw error;
          }
        };
        for (const eventType of eventTypes) {
          installListener(eventType);
        }
        interface WritableBindingTarget {
          readonly componentId: ComponentId;
          readonly binding: BindingName;
          readonly snapshot: StateBindingSnapshot;
          readonly key: string;
        }
        const resolveWritableBinding = (
          rawComponentId: string,
          rawBinding: string,
        ): Effect.Effect<
          WritableBindingTarget,
          | ResumeBindingSnapshotNotFoundError
          | ResumeBindingSnapshotNotWritableError
          | ResumeBindingSnapshotWriteDisposedError
        > =>
          Effect.gen(function* () {
            if (disposed) {
              return yield* new ResumeBindingSnapshotWriteDisposedError({
                componentId: rawComponentId,
                binding: rawBinding,
                message: `Binding "${rawComponentId}/${rawBinding}" was written after the client installation was disposed.`,
              });
            }
            const component = componentSnapshots[
              rawComponentId as ComponentId
            ];
            const snapshot = component?.bindings[
              rawBinding as BindingName
            ];
            if (component === undefined || snapshot === undefined) {
              return yield* new ResumeBindingSnapshotNotFoundError({
                componentId: rawComponentId,
                binding: rawBinding,
                message: `No binding snapshot exists for "${rawComponentId}/${rawBinding}".`,
              });
            }
            const componentId =
              componentIdFromValidatedString(rawComponentId);
            const binding = bindingNameFromValidatedString(rawBinding);
            const controller = controllers.get(componentId);
            if (
              snapshot.kind !== "state"
              || controller?.state.status !== "dormant"
              || controller.quiescedBy !== undefined
            ) {
              return yield* new ResumeBindingSnapshotNotWritableError({
                componentId,
                binding,
                message: snapshot.kind !== "state"
                  ? `Binding "${componentId}/${binding}" is a query snapshot and cannot be written as state.`
                  : `Binding "${componentId}/${binding}" is no longer dormant and is owned by the component runtime.`,
              });
            }
            const key = bindingReactivityKey(componentId, binding);
            return {
              componentId,
              binding,
              snapshot,
              key,
            };
          });
        const commitBindingWrite = (
          target: WritableBindingTarget,
          encodedValue: unknown,
        ): Effect.Effect<
          void,
          | ResumeBindingSnapshotNotWritableError
          | ResumeBindingSnapshotWriteDisposedError
          | ResumeBindingSnapshotWriteEncodeError
        > =>
          Effect.gen(function* () {
            // Encoding may be effectful. Re-check ownership at the commit
            // point so a write that started while dormant cannot mutate the
            // snapshot after activation or installation disposal.
            if (disposed) {
              return yield* new ResumeBindingSnapshotWriteDisposedError({
                componentId: target.componentId,
                binding: target.binding,
                message: `Binding "${target.componentId}/${target.binding}" was written after the client installation was disposed.`,
              });
            }
            if (
              controllers.get(target.componentId)?.state.status !== "dormant"
              || controllers.get(target.componentId)?.quiescedBy !== undefined
            ) {
              return yield* new ResumeBindingSnapshotNotWritableError({
                componentId: target.componentId,
                binding: target.binding,
                message: `Binding "${target.componentId}/${target.binding}" is no longer dormant and is owned by the component runtime.`,
              });
            }
            const issue = jsonValueIssue(
              encodedValue,
              `Binding "${target.componentId}/${target.binding}"`,
            );
            if (issue !== undefined) {
              return yield* new ResumeBindingSnapshotWriteEncodeError({
                componentId: target.componentId,
                binding: target.binding,
                message: issue,
              });
            }
            if (Object.is(bindingValues.get(target.key), encodedValue)) {
              return;
            }
            bindingValues.set(target.key, encodedValue);
            let componentOverrides = bindingOverrides.get(
              target.componentId,
            );
            if (componentOverrides === undefined) {
              componentOverrides = new Map();
              bindingOverrides.set(target.componentId, componentOverrides);
            }
            componentOverrides.set(target.binding, encodedValue);
            notifyExpressions([target.key], true);
          });
        const writeBindingEncoded: ClientInstallation["writeBindingEncoded"] = (
          rawComponentId,
          rawBinding,
          encodedValue,
        ) =>
          resolveWritableBinding(rawComponentId, rawBinding).pipe(
            Effect.flatMap((target) =>
              commitBindingWrite(target, encodedValue)
            ),
          );
        const writeBinding: ClientInstallation["writeBinding"] = (
          rawComponentId,
          rawBinding,
          schema,
          value,
        ) =>
          Effect.gen(function* () {
            const target = yield* resolveWritableBinding(
              rawComponentId,
              rawBinding,
            );
            const encodedValue = yield* Schema.encodeEffect(schema)(
              value,
            ).pipe(
              Effect.catchTag("SchemaError", (error) =>
                Effect.fail(
                  new ResumeBindingSnapshotWriteEncodeError({
                    componentId: rawComponentId,
                    binding: rawBinding,
                    message: `Binding "${rawComponentId}/${rawBinding}" could not encode the written value: ${String(error)}`,
                  }),
                ),
              ),
            );
            yield* commitBindingWrite(target, encodedValue);
          });
        const dispose = Effect.suspend(() => {
          if (disposed) return Effect.void;
          disposed = true;
          stopExpressionInvalidation();
          for (const [eventType, listener] of listeners) {
            removeListener(eventType, listener);
          }
          listeners.clear();
          bindingValues.clear();
          bindingOverrides.clear();
          if (
            activeClientInstallations.get(options.root) === installationToken
          ) {
            activeClientInstallations.delete(options.root);
          }
          return Effect.forEach(
            controllers.values(),
            disposeBoundary,
            { discard: true },
          ).pipe(
            Effect.andThen(
              Effect.forEach(
                [...expressionControllers.values()],
                disposeExpression,
                { discard: true },
              ),
            ),
            Effect.andThen(
              Effect.suspend(() => {
                const running = [...fibers];
                fibers.clear();
                return Effect.forEach(running, Fiber.interrupt, {
                  discard: true,
                });
              }),
            ),
          );
        });

        const inspect = (): ClientInstallationInspection => {
          const boundaryCounts: {
            -readonly [Status in keyof ClientInstallationBoundaryCounts]:
              number;
          } = {
            dormant: 0,
            resuming: 0,
            activating: 0,
            active: 0,
            failed: 0,
            disposed: 0,
          };
          let boundarySubscribers = 0;
          let boundaryControllers = 0;
          for (const controller of controllers.values()) {
            boundaryCounts[controller.state.status] += 1;
            boundarySubscribers += controller.subscribers.size;
            if (controller.state.status !== "disposed") {
              boundaryControllers += 1;
            }
          }
          let expressionSubscriptions = 0;
          for (const subscribers of expressionSubscribers.values()) {
            expressionSubscriptions += subscribers.size;
          }
          let runningExpressions = 0;
          let queuedExpressions = 0;
          for (const controller of expressionControllers.values()) {
            if (controller.running !== undefined) runningExpressions += 1;
            if (controller.queued) queuedExpressions += 1;
          }
          let bindingOverrideCount = 0;
          for (const overrides of bindingOverrides.values()) {
            bindingOverrideCount += overrides.size;
          }
          return {
            disposed,
            pendingFibers: fibers.size,
            eventListeners: listeners.size,
            boundaryControllers,
            boundarySubscribers,
            boundaries: boundaryCounts,
            expressionControllers: expressionControllers.size,
            expressionDependencyKeys: expressionSubscribers.size,
            expressionSubscriptions,
            runningExpressions,
            queuedExpressions,
            bindingValues: bindingValues.size,
            bindingOverrides: bindingOverrideCount,
          };
        };

        const installation: ClientInstallation = {
          pending: () => fibers.size,
          inspect,
          boundaries,
          boundaryState: (componentId: string) =>
            controllers.get(componentId as ComponentId)?.state,
          activate,
          resume: resumeBoundary,
          writeBinding,
          writeBindingEncoded,
          dispose,
        };
        clientInstallationFragmentInternals.set(installation, {
          root: options.root,
          expectedBuildId,
          report,
          fragmentScopes,
          regionFragments,
          mintFragmentScope: () => `f${++fragmentScopeCounter}`,
          installListener: (eventType) => installListener(eventType as EventType),
        });
        return installation;
      },
      catch: (error) =>
        new ResumeListenerInstallError({
          message: `Resume event listener installation failed: ${String(error)}`,
        }),
    });
  });
}

